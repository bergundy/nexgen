//! Per-language emitters.
//!
//! Each submodule implements [`nex_gen_core::Emitter<Kind>`] for one target,
//! rendering the lowered [`Kind`](crate::ir::Kind) symbols into complete file
//! bodies (import block included). This module holds the shared plumbing every
//! emitter reuses: symbol iteration order, doc-comment reflow, and small string
//! helpers.

pub mod go;
pub mod java;
pub mod python;
pub mod typescript;

use nex_gen_core::{IR, Service, Symbol, SymbolId};

use crate::ir::{Kind, MapType, Record};

/// The generated-file banner (Go/TS/Python form).
pub const BANNER: &str = "Code generated by nex-gen. DO NOT EDIT.";

/// Package/module naming derived from the input file(s), threaded to every
/// emitter (the core IR carries no file identity, so this travels alongside).
#[derive(Clone, Debug)]
pub struct PackageInfo {
    /// The flat module/package name, e.g. `chat` from `chat.nexusrpc.yaml`.
    pub name: String,
    /// The Java package, e.g. `com.example.chat`.
    pub java_package: String,
}

impl PackageInfo {
    /// Derive package naming from the primary input path. The module name is
    /// the filename up to its first `.` (`chat.nexusrpc.yaml` → `chat`).
    pub fn from_input(path: &std::path::Path) -> Self {
        let file = path
            .file_name()
            .map(|s| s.to_string_lossy().into_owned())
            .unwrap_or_else(|| "schema".to_string());
        let name = file.split('.').next().unwrap_or("schema").to_string();
        let java_package = format!("com.example.{name}");
        Self { name, java_package }
    }
}

/// The named type symbols (records + maps) in id order, paired with their id.
pub fn type_symbols(ir: &IR<Kind>) -> Vec<&Symbol<Kind>> {
    ir.symbols
        .iter()
        .filter(|s| matches!(s.kind, Kind::Record(_) | Kind::Map(_)))
        .collect()
}

/// The service symbols in id order.
pub fn services(ir: &IR<Kind>) -> Vec<&Service> {
    ir.symbols
        .iter()
        .filter_map(|s| match &s.kind {
            Kind::Service(svc) => Some(svc),
            _ => None,
        })
        .collect()
}

/// Look up a symbol's canonical name by id.
pub fn symbol_name<'a>(ir: &'a IR<Kind>, id: SymbolId) -> &'a str {
    ir.symbols.get(id).map(|s| s.name.as_str()).unwrap_or("Unknown")
}

/// Whether a symbol is a [`Record`].
pub fn as_record(symbol: &Symbol<Kind>) -> Option<&Record> {
    match &symbol.kind {
        Kind::Record(r) => Some(r),
        _ => None,
    }
}

/// Whether a symbol is a [`MapType`].
pub fn as_map(symbol: &Symbol<Kind>) -> Option<&MapType> {
    match &symbol.kind {
        Kind::Map(m) => Some(m),
        _ => None,
    }
}

/// Reflow a doc string into lines (trimmed, blank lines preserved as empty).
pub fn doc_lines(docs: &str) -> Vec<String> {
    docs.trim().lines().map(|l| l.trim().to_string()).collect()
}
