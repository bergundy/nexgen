//! The Java emitter.
//!
//! Emits one `.java` file per public type plus the three shared boilerplate
//! classes (`ValidationException`, `Violation`, `SpecNumbers`) and one
//! interface per Nexus service. Every model class carries class-level
//! `@JsonDeserialize`/`@JsonSerialize` bound to nested collecting
//! (de)serializers that aggregate `Violation`s into a `ValidationException`
//! (Java §5). JSpecify `@NullMarked` packages; optional/nullable references are
//! `@Nullable`.

use std::path::PathBuf;

use nex_gen_core::{Emitter, EmittedFile, IR, Language, Result, Service};

use crate::emit::{PackageInfo, as_map, as_record, services, symbol_name, type_symbols};
use crate::ir::{Additional, Field, FieldType, Kind, MapType, Record, Scalar};
use crate::naming;

pub fn emitter(pkg: PackageInfo) -> Box<dyn Emitter<Kind>> {
    Box::new(JavaEmitter { pkg })
}

struct JavaEmitter {
    pkg: PackageInfo,
}

impl Emitter<Kind> for JavaEmitter {
    fn language(&self) -> Language {
        Language::Java
    }

    fn emit(&self, ir: &IR<Kind>) -> Result<Vec<EmittedFile>> {
        let pkg = &self.pkg.java_package;
        let mut files = Vec::new();

        files.push(self.file("ValidationException", validation_exception(pkg)));
        files.push(self.file("Violation", violation(pkg)));
        files.push(self.file("SpecNumbers", spec_numbers(pkg)));

        for symbol in type_symbols(ir) {
            let name = naming::type_ident(symbol.name.as_str(), Language::Java, &Default::default());
            let body = if let Some(record) = as_record(symbol) {
                render_record(ir, pkg, &name, record)
            } else if let Some(map) = as_map(symbol) {
                render_map(pkg, &name, map)
            } else {
                continue;
            };
            files.push(self.file(&name, body));
        }

        for svc in services(ir) {
            let name = naming::type_ident(svc.name.as_str(), Language::Java, &Default::default());
            files.push(self.file(&name, render_service(ir, pkg, svc)));
        }

        Ok(files)
    }
}

impl JavaEmitter {
    fn file(&self, class: &str, body: String) -> EmittedFile {
        let dir = self.pkg.java_package.replace('.', "/");
        EmittedFile {
            path: PathBuf::from(format!("{dir}/{class}.java")),
            body,
        }
    }
}

const HEADER: &str = "// Generated by nex-gen. DO NOT EDIT!\n";

// ---------------------------------------------------------------------------
// Java type mapping.
// ---------------------------------------------------------------------------

fn java_type(ir: &IR<Kind>, ty: &FieldType) -> String {
    match ty {
        FieldType::String => "String".to_string(),
        FieldType::Integer => "Long".to_string(),
        FieldType::Number => "Double".to_string(),
        FieldType::Boolean => "Boolean".to_string(),
        FieldType::Array(inner) => format!("List<{}>", java_type(ir, inner)),
        FieldType::Ref(id) => {
            naming::type_ident(symbol_name(ir, *id), Language::Java, &Default::default())
        }
    }
}

/// A field's declared class name (const fields get their own nested value class).
fn field_class(field: &Field) -> Option<String> {
    if matches!(field.constant, Some(Scalar::String(_))) && matches!(field.ty, FieldType::String) {
        Some(naming::type_ident(&field.json_name, Language::Java, &field.overrides))
    } else {
        None
    }
}

fn field_ident(field: &Field) -> String {
    naming::field_ident(&field.json_name, Language::Java, &field.overrides)
}

