fn render_map(pkg: &str, name: &str, map: &MapType) -> String {
    let value_ty = "String";
    let max = map.max_properties;
    let mut out = String::new();
    out.push_str(HEADER);
    out.push('\n');
    out.push_str(&format!("package {pkg};\n\n"));
    out.push_str(&map_imports());
    out.push('\n');
    push_doc(&mut out, map.docs.as_deref(), "");
    out.push_str("@NullMarked\n");
    out.push_str(&format!("@JsonDeserialize(using = {name}.Deserializer.class)\n"));
    out.push_str(&format!("@JsonSerialize(using = {name}.Serializer.class)\n"));
    out.push_str(&format!("public final class {name} {{\n"));
    if let Some(max) = max {
        out.push_str(&format!("  private static final int MAX_PROPERTIES = {max};\n\n"));
    }
    out.push_str(&format!("  private final Map<String, {value_ty}> additionalProperties;\n\n"));
    out.push_str(&format!("  public {name}(Map<String, {value_ty}> additionalProperties) {{\n    this.additionalProperties = additionalProperties;\n  }}\n\n"));
    out.push_str(&format!("  public Map<String, {value_ty}> getAdditionalProperties() {{\n    return Collections.unmodifiableMap(additionalProperties);\n  }}\n\n"));

    out.push_str(&format!("  public static final class Deserializer extends JsonDeserializer<{name}> {{\n"));
    out.push_str("    @Override\n");
    out.push_str(&format!("    public {name} deserialize(JsonParser p, DeserializationContext ctx) throws IOException {{\n"));
    out.push_str("      JsonNode root = p.readValueAsTree();\n      List<Violation> errs = new ArrayList<>();\n");
    out.push_str(&format!("      Map<String, {value_ty}> map = new LinkedHashMap<>();\n"));
    out.push_str("      Iterator<Map.Entry<String, JsonNode>> it = root.fields();\n");
    out.push_str("      while (it.hasNext()) {\n        Map.Entry<String, JsonNode> e = it.next();\n        JsonNode val = e.getValue();\n");
    out.push_str("        if (!val.isTextual()) {\n          errs.add(new Violation(e.getKey(), \"expected string\"));\n        } else {\n          map.put(e.getKey(), val.asText());\n        }\n      }\n");
    if let Some(max) = max {
        out.push_str(&format!("      if (map.size() > MAX_PROPERTIES) {{\n        errs.add(new Violation(\"\", \"maxProperties: at most {max} entries\"));\n      }}\n"));
    }
    out.push_str("      if (!errs.isEmpty()) {\n        throw new ValidationException(p, errs);\n      }\n");
    out.push_str(&format!("      return new {name}(map);\n    }}\n  }}\n\n"));

    out.push_str(&format!("  public static final class Serializer extends JsonSerializer<{name}> {{\n"));
    out.push_str("    @Override\n");
    out.push_str(&format!("    public void serialize({name} v, JsonGenerator gen, SerializerProvider sp) throws IOException {{\n"));
    if let Some(max) = max {
        out.push_str(&format!("      if (v.additionalProperties.size() > MAX_PROPERTIES) {{\n        throw new ValidationException(\n            null,\n            List.of(new Violation(\"\", \"maxProperties: at most {max} entries\")));\n      }}\n"));
    }
    out.push_str("      gen.writeStartObject();\n");
    out.push_str(&format!("      for (Map.Entry<String, {value_ty}> e : v.additionalProperties.entrySet()) {{\n        gen.writeStringField(e.getKey(), e.getValue());\n      }}\n"));
    out.push_str("      gen.writeEndObject();\n    }\n  }\n");
    out.push_str("}\n");
    out
}

// ---------------------------------------------------------------------------
// Service interface.
// ---------------------------------------------------------------------------

fn render_service(ir: &IR<Kind>, pkg: &str, svc: &Service) -> String {
    let mut out = String::new();
    out.push_str(HEADER);
    out.push('\n');
    out.push_str(&format!("package {pkg};\n\n"));
    out.push_str("import io.nexusrpc.Operation;\nimport io.nexusrpc.Service;\nimport org.jspecify.annotations.NullMarked;\n\n");
    push_doc(&mut out, svc.docs.as_deref(), "");
    out.push_str("@NullMarked\n");
    out.push_str(&format!("@Service(name = \"{}\")\n", svc.wire_name));
    let name = naming::type_ident(svc.name.as_str(), Language::Java, &Default::default());
    out.push_str(&format!("public interface {name} {{\n"));
    for op in &svc.operations {
        push_doc(&mut out, op.docs.as_deref(), "  ");
        out.push_str(&format!("  @Operation(name = \"{}\")\n", op.wire_name));
        let method = naming::field_ident(op.name.as_str(), Language::Java, &Default::default());
        let ret = op
            .output
            .map(|id| naming::type_ident(symbol_name(ir, id), Language::Java, &Default::default()))
            .unwrap_or_else(|| "void".to_string());
        match op.input {
            Some(id) => {
                let input =
                    naming::type_ident(symbol_name(ir, id), Language::Java, &Default::default());
                out.push_str(&format!("  {ret} {method}({input} input);\n\n"));
            }
            None => out.push_str(&format!("  {ret} {method}();\n\n")),
        }
    }
    while out.ends_with("\n\n") {
        out.pop();
    }
    out.push_str("}\n");
    out
}

