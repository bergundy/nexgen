fn render_record(ir: &IR<Kind>, pkg: &str, name: &str, record: &Record) -> String {
    let open = matches!(record.additional, Additional::Open);
    let mut out = String::new();
    out.push_str(HEADER);
    out.push('\n');
    out.push_str(&format!("package {pkg};\n\n"));
    out.push_str(&model_imports(record, open));
    out.push('\n');
    push_doc(&mut out, record.docs.as_deref(), "");
    out.push_str("@NullMarked\n");
    out.push_str(&format!("@JsonDeserialize(using = {name}.Deserializer.class)\n"));
    out.push_str(&format!("@JsonSerialize(using = {name}.Serializer.class)\n"));
    out.push_str(&format!("public final class {name} {{\n"));

    if open {
        let names: Vec<String> = record
            .fields
            .iter()
            .map(|f| format!("\"{}\"", f.json_name))
            .collect();
        out.push_str(&format!(
            "  private static final java.util.Set<String> DECLARED =\n      new java.util.HashSet<>(java.util.Arrays.asList({}));\n\n",
            names.join(", ")
        ));
    }

    for field in &record.fields {
        if let Some(cls) = field_class(field) {
            if let Some(Scalar::String(value)) = &field.constant {
                out.push_str(&value_class(&cls, value));
            }
        }
    }

    for field in &record.fields {
        let ident = field_ident(field);
        if let Some(cls) = field_class(field) {
            let value = const_value_name(field);
            out.push_str(&format!("  private final {cls} {ident} = {cls}.{value};\n"));
        } else {
            let ty = java_type(ir, &field.ty);
            let nullable = !field.required || field.nullable;
            let ann = if nullable { "@Nullable " } else { "" };
            out.push_str(&format!("  private final {ann}{ty} {ident};\n"));
        }
    }
    if open {
        out.push_str("  private final Map<String, Object> additionalProperties;\n");
    }
    out.push('\n');

    let ctor_params = ctor_params(ir, record, open);
    out.push_str(&format!("  public {name}({}) {{\n", ctor_params.join(", ")));
    for field in &record.fields {
        if field_class(field).is_some() {
            continue;
        }
        let ident = field_ident(field);
        out.push_str(&format!("    this.{ident} = {ident};\n"));
    }
    if open {
        out.push_str("    this.additionalProperties = additionalProperties;\n");
    }
    out.push_str("  }\n\n");

    for field in &record.fields {
        let ident = field_ident(field);
        let getter = format!("get{}", pascal(&ident));
        push_doc(&mut out, field.docs.as_deref(), "  ");
        if let Some(cls) = field_class(field) {
            out.push_str(&format!("  public {cls} {getter}() {{\n    return {ident};\n  }}\n\n"));
        } else if let Some(default) = &field.default {
            let (ret, expr) = default_getter(ir, field, default);
            out.push_str(&format!("  public {ret} {getter}() {{\n    return {expr};\n  }}\n\n"));
        } else {
            let ty = java_type(ir, &field.ty);
            let nullable = !field.required || field.nullable;
            let ann = if nullable { "@Nullable " } else { "" };
            out.push_str(&format!("  public {ann}{ty} {getter}() {{\n    return {ident};\n  }}\n\n"));
        }
    }
    if open {
        out.push_str("  /** Undeclared members preserved verbatim for forward compatibility. */\n");
        out.push_str("  public Map<String, Object> getAdditionalProperties() {\n    return Collections.unmodifiableMap(additionalProperties);\n  }\n\n");
    }

    out.push_str(&record_deserializer(ir, name, record, open));
    out.push('\n');
    out.push_str(&record_serializer(ir, name, record, open));

    out.push_str("}\n");
    out
}

fn ctor_params(ir: &IR<Kind>, record: &Record, open: bool) -> Vec<String> {
    let mut params = Vec::new();
    for field in &record.fields {
        if field_class(field).is_some() {
            continue;
        }
        let ty = java_type(ir, &field.ty);
        let ident = field_ident(field);
        let nullable = !field.required || field.nullable;
        let ann = if nullable { "@Nullable " } else { "" };
        params.push(format!("{ann}{ty} {ident}"));
    }
    if open {
        params.push("Map<String, Object> additionalProperties".to_string());
    }
    params
}

fn const_value_name(field: &Field) -> String {
    match &field.constant {
        Some(Scalar::String(s)) => s.to_uppercase().replace(|c: char| !c.is_alphanumeric(), "_"),
        _ => "VALUE".to_string(),
    }
}

fn default_getter(ir: &IR<Kind>, field: &Field, default: &Scalar) -> (String, String) {
    let ident = field_ident(field);
    match (&field.ty, default) {
        (FieldType::Integer, Scalar::Integer(v)) => {
            ("long".to_string(), format!("{ident} != null ? {ident} : {v}L"))
        }
        (FieldType::Number, Scalar::Number(v)) => {
            ("double".to_string(), format!("{ident} != null ? {ident} : {v}"))
        }
        (FieldType::Boolean, Scalar::Boolean(v)) => {
            ("boolean".to_string(), format!("{ident} != null ? {ident} : {v}"))
        }
        (FieldType::String, Scalar::String(v)) => (
            "String".to_string(),
            format!("{ident} != null ? {ident} : \"{v}\""),
        ),
        _ => (java_type(ir, &field.ty), ident),
    }
}

fn value_class(cls: &str, value: &str) -> String {
    let upper = value.to_uppercase().replace(|c: char| !c.is_alphanumeric(), "_");
    format!(
        r#"  /**
   * Open value class for the discriminator (const "{value}"). Any wire value is
   * representable for forward compatibility; the validator rejects anything but
   * {{@link #{upper}}} because a const is a closed contract.
   */
  public static final class {cls} {{
    public static final {cls} {upper} = new {cls}("{value}");

    private final String value;

    private {cls}(String value) {{
      this.value = value;
    }}

    @JsonCreator
    public static @Nullable {cls} fromString(@Nullable String v) {{
      if (v == null) {{
        return null;
      }}
      if (v.equals("{value}")) {{
        return {upper};
      }}
      return new {cls}(v);
    }}

    @JsonValue
    public String getValue() {{
      return value;
    }}

    public boolean isUnrecognized() {{
      return this != {upper};
    }}

    @Override
    public boolean equals(@Nullable Object o) {{
      return o instanceof {cls} && value.equals((({cls}) o).value);
    }}

    @Override
    public int hashCode() {{
      return value.hashCode();
    }}

    @Override
    public String toString() {{
      return value;
    }}
  }}

"#
    )
}

fn record_deserializer(ir: &IR<Kind>, name: &str, record: &Record, open: bool) -> String {
    let mut out = String::new();
    out.push_str(&format!("  public static final class Deserializer extends JsonDeserializer<{name}> {{\n"));
    out.push_str("    @Override\n");
    out.push_str(&format!("    public {name} deserialize(JsonParser p, DeserializationContext ctx) throws IOException {{\n"));
    out.push_str("      JsonNode root = p.readValueAsTree();\n");
    out.push_str("      List<Violation> errs = new ArrayList<>();\n\n");

    for field in &record.fields {
        out.push_str(&deser_field(ir, field));
        out.push('\n');
    }

    if open {
        out.push_str("      Map<String, Object> extra = new LinkedHashMap<>();\n");
        out.push_str("      Iterator<Map.Entry<String, JsonNode>> extraIt = root.fields();\n");
        out.push_str("      while (extraIt.hasNext()) {\n");
        out.push_str("        Map.Entry<String, JsonNode> e = extraIt.next();\n");
        out.push_str("        if (!DECLARED.contains(e.getKey())) {\n");
        out.push_str("          extra.put(e.getKey(), ctx.readTreeAsValue(e.getValue(), Object.class));\n");
        out.push_str("        }\n      }\n\n");
    } else if matches!(record.additional, Additional::Closed) {
        let names: Vec<String> = record
            .fields
            .iter()
            .map(|f| format!("!key.equals(\"{}\")", f.json_name))
            .collect();
        out.push_str("      Iterator<String> keyIt = root.fieldNames();\n");
        out.push_str("      while (keyIt.hasNext()) {\n");
        out.push_str("        String key = keyIt.next();\n");
        if names.is_empty() {
            out.push_str("        errs.add(new Violation(key, \"unknown field\"));\n");
        } else {
            out.push_str(&format!("        if ({}) {{\n", names.join(" && ")));
            out.push_str("          errs.add(new Violation(key, \"unknown field\"));\n        }\n");
        }
        out.push_str("      }\n\n");
    }

    out.push_str("      if (!errs.isEmpty()) {\n        throw new ValidationException(p, errs);\n      }\n");
    let args = ctor_args(record, open);
    out.push_str(&format!("      return new {name}({});\n", args.join(", ")));
    out.push_str("    }\n  }\n");
    out
}

fn ctor_args(record: &Record, open: bool) -> Vec<String> {
    let mut args = Vec::new();
    for field in &record.fields {
        if field_class(field).is_some() {
            continue;
        }
        let ident = field_ident(field);
        if field.required && !field.nullable {
            args.push(format!("Objects.requireNonNull({ident})"));
        } else {
            args.push(ident);
        }
    }
    if open {
        args.push("extra".to_string());
    }
    args
}

fn deser_field(ir: &IR<Kind>, field: &Field) -> String {
    let ident = field_ident(field);
    let json = &field.json_name;
    let node = format!("{ident}Node");

    if let Some(cls) = field_class(field) {
        if let Some(Scalar::String(value)) = &field.constant {
            return format!(
                "      JsonNode {node} = root.get(\"{json}\");\n\
                 \x20     if ({node} == null || {node}.isNull()) {{\n\
                 \x20       errs.add(new Violation(\"{json}\", \"required\"));\n\
                 \x20     }} else if (!{node}.isTextual()) {{\n\
                 \x20       errs.add(new Violation(\"{json}\", \"expected string\"));\n\
                 \x20     }} else {{\n\
                 \x20       {cls} k = {cls}.fromString({node}.asText());\n\
                 \x20       if (k == null || k.isUnrecognized()) {{\n\
                 \x20         errs.add(new Violation(\"{json}\", \"const: expected \\\"{value}\\\"\"));\n\
                 \x20       }}\n\
                 \x20     }}\n"
            );
        }
    }

    match &field.ty {
        FieldType::String => deser_string(field, &ident, json, &node),
        FieldType::Integer => deser_integer(field, &ident, json, &node),
        FieldType::Number => {
            deser_generic_number(field, &ident, json, &node, "Double", "isNumber", "doubleValue")
        }
        FieldType::Boolean => deser_bool(field, &ident, json, &node),
        FieldType::Array(inner) => deser_array(ir, field, inner, &ident, json, &node),
        FieldType::Ref(id) => {
            let cls = naming::type_ident(symbol_name(ir, *id), Language::Java, &Default::default());
            deser_ref(field, &cls, &ident, json, &node)
        }
    }
}

fn deser_string(field: &Field, ident: &str, json: &str, node: &str) -> String {
    let mut out = format!("      String {ident} = null;\n");
    out.push_str(&format!("      JsonNode {node} = root.get(\"{json}\");\n"));
    if field.required && !field.nullable {
        out.push_str(&format!("      if ({node} == null || {node}.isNull()) {{\n        errs.add(new Violation(\"{json}\", \"required\"));\n      }} else if (!{node}.isTextual()) {{\n        errs.add(new Violation(\"{json}\", \"expected string\"));\n      }} else {{\n        {ident} = {node}.asText();\n      }}\n"));
    } else if field.required && field.nullable {
        out.push_str(&format!("      if ({node} == null) {{\n        errs.add(new Violation(\"{json}\", \"required\"));\n      }} else if (!{node}.isNull()) {{\n        if (!{node}.isTextual()) {{\n          errs.add(new Violation(\"{json}\", \"expected string\"));\n        }} else {{\n          {ident} = {node}.asText();\n        }}\n      }}\n"));
    } else if !field.nullable {
        out.push_str(&format!("      if ({node} != null) {{\n        if ({node}.isNull()) {{\n          errs.add(new Violation(\"{json}\", \"explicit null not allowed\"));\n        }} else if (!{node}.isTextual()) {{\n          errs.add(new Violation(\"{json}\", \"expected string\"));\n        }} else {{\n          {ident} = {node}.asText();\n        }}\n      }}\n"));
    } else {
        out.push_str(&format!("      if ({node} != null && !{node}.isNull()) {{\n        if (!{node}.isTextual()) {{\n          errs.add(new Violation(\"{json}\", \"expected string\"));\n        }} else {{\n          {ident} = {node}.asText();\n        }}\n      }}\n"));
    }
    out
}

fn deser_integer(field: &Field, ident: &str, json: &str, node: &str) -> String {
    let mut out = format!("      Long {ident} = null;\n");
    out.push_str(&format!("      JsonNode {node} = root.get(\"{json}\");\n"));
    if field.required && !field.nullable {
        out.push_str(&format!("      if ({node} == null || {node}.isNull()) {{\n        errs.add(new Violation(\"{json}\", \"required\"));\n      }} else {{\n        {ident} = SpecNumbers.specLong({node}, \"{json}\", errs);\n      }}\n"));
    } else if !field.nullable {
        out.push_str(&format!("      if ({node} != null) {{\n        if ({node}.isNull()) {{\n          errs.add(new Violation(\"{json}\", \"explicit null not allowed\"));\n        }} else {{\n          {ident} = SpecNumbers.specLong({node}, \"{json}\", errs);\n        }}\n      }}\n"));
    } else {
        out.push_str(&format!("      if ({node} != null && !{node}.isNull()) {{\n        {ident} = SpecNumbers.specLong({node}, \"{json}\", errs);\n      }}\n"));
    }
    out
}

fn deser_generic_number(
    field: &Field,
    ident: &str,
    json: &str,
    node: &str,
    ty: &str,
    check: &str,
    getter: &str,
) -> String {
    let mut out = format!("      {ty} {ident} = null;\n");
    out.push_str(&format!("      JsonNode {node} = root.get(\"{json}\");\n"));
    let assign = format!("{ident} = {node}.{getter}();");
    if field.required && !field.nullable {
        out.push_str(&format!("      if ({node} == null || {node}.isNull()) {{\n        errs.add(new Violation(\"{json}\", \"required\"));\n      }} else if (!{node}.{check}()) {{\n        errs.add(new Violation(\"{json}\", \"expected number\"));\n      }} else {{\n        {assign}\n      }}\n"));
    } else {
        out.push_str(&format!("      if ({node} != null && !{node}.isNull()) {{\n        if (!{node}.{check}()) {{\n          errs.add(new Violation(\"{json}\", \"expected number\"));\n        }} else {{\n          {assign}\n        }}\n      }}\n"));
    }
    out
}

fn deser_bool(field: &Field, ident: &str, json: &str, node: &str) -> String {
    let mut out = format!("      Boolean {ident} = null;\n");
    out.push_str(&format!("      JsonNode {node} = root.get(\"{json}\");\n"));
    if field.required && !field.nullable {
        out.push_str(&format!("      if ({node} == null || {node}.isNull()) {{\n        errs.add(new Violation(\"{json}\", \"required\"));\n      }} else if (!{node}.isBoolean()) {{\n        errs.add(new Violation(\"{json}\", \"expected boolean\"));\n      }} else {{\n        {ident} = {node}.asBoolean();\n      }}\n"));
    } else {
        out.push_str(&format!("      if ({node} != null && !{node}.isNull()) {{\n        if (!{node}.isBoolean()) {{\n          errs.add(new Violation(\"{json}\", \"expected boolean\"));\n        }} else {{\n          {ident} = {node}.asBoolean();\n        }}\n      }}\n"));
    }
    out
}

fn deser_array(
    ir: &IR<Kind>,
    _field: &Field,
    inner: &FieldType,
    ident: &str,
    json: &str,
    node: &str,
) -> String {
    let elem_ty = java_type(ir, inner);
    let mut out = format!("      List<{elem_ty}> {ident} = null;\n");
    out.push_str(&format!("      JsonNode {node} = root.get(\"{json}\");\n"));
    out.push_str(&format!("      if ({node} != null && !{node}.isNull()) {{\n"));
    out.push_str(&format!("        if (!{node}.isArray()) {{\n          errs.add(new Violation(\"{json}\", \"expected array\"));\n        }} else {{\n"));
    out.push_str(&format!("          {ident} = new ArrayList<>();\n"));
    out.push_str(&format!("          for (int i = 0; i < {node}.size(); i++) {{\n            JsonNode item = {node}.get(i);\n"));
    match inner {
        FieldType::String => {
            out.push_str(&format!("            if (!item.isTextual()) {{\n              errs.add(new Violation(\"{json}[\" + i + \"]\", \"expected string\"));\n            }} else {{\n              {ident}.add(item.asText());\n            }}\n"));
        }
        _ => {
            out.push_str(&format!("            {ident}.add(ctx.readTreeAsValue(item, {elem_ty}.class));\n"));
        }
    }
    out.push_str("          }\n        }\n      }\n");
    out
}

fn deser_ref(field: &Field, cls: &str, ident: &str, json: &str, node: &str) -> String {
    let mut out = format!("      {cls} {ident} = null;\n");
    out.push_str(&format!("      JsonNode {node} = root.get(\"{json}\");\n"));
    let body = format!(
        "        try {{\n          {ident} = ctx.readTreeAsValue({node}, {cls}.class);\n        }} catch (ValidationException nested) {{\n          for (Violation v : nested.getViolations()) {{\n            errs.add(new Violation(\"{json}.\" + v.getPath(), v.getReason()));\n          }}\n        }}\n"
    );
    if field.required && !field.nullable {
        out.push_str(&format!("      if ({node} == null || {node}.isNull()) {{\n        errs.add(new Violation(\"{json}\", \"required\"));\n      }} else {{\n{body}      }}\n"));
    } else {
        out.push_str(&format!("      if ({node} != null && !{node}.isNull()) {{\n{body}      }}\n"));
    }
    out
}

fn record_serializer(ir: &IR<Kind>, name: &str, record: &Record, open: bool) -> String {
    let mut out = String::new();
    out.push_str(&format!("  public static final class Serializer extends JsonSerializer<{name}> {{\n"));
    out.push_str("    @Override\n");
    out.push_str(&format!("    public void serialize({name} v, JsonGenerator gen, SerializerProvider sp) throws IOException {{\n"));
    out.push_str("      List<Violation> errs = new ArrayList<>();\n");
    for field in &record.fields {
        if field_class(field).is_some() {
            continue;
        }
        if field.required && !field.nullable {
            out.push_str(&format!("      if (v.{} == null) {{\n        errs.add(new Violation(\"{}\", \"required\"));\n      }}\n", field_ident(field), field.json_name));
        }
    }
    out.push_str("      if (!errs.isEmpty()) {\n        throw new ValidationException(null, errs);\n      }\n\n");
    out.push_str("      gen.writeStartObject();\n");
    for field in &record.fields {
        out.push_str(&ser_field(ir, field));
    }
    if open {
        out.push_str("      for (Map.Entry<String, Object> e : v.additionalProperties.entrySet()) {\n");
        out.push_str("        gen.writeFieldName(e.getKey());\n        sp.defaultSerializeValue(e.getValue(), gen);\n      }\n");
    }
    out.push_str("      gen.writeEndObject();\n");
    out.push_str("    }\n  }\n");
    out
}

fn ser_field(ir: &IR<Kind>, field: &Field) -> String {
    let ident = field_ident(field);
    let json = &field.json_name;

    if field_class(field).is_some() {
        return format!("      gen.writeStringField(\"{json}\", v.{ident}.getValue());\n");
    }

    match &field.ty {
        FieldType::String => {
            if field.required && field.nullable {
                format!("      if (v.{ident} == null) {{\n        gen.writeNullField(\"{json}\");\n      }} else {{\n        gen.writeStringField(\"{json}\", v.{ident});\n      }}\n")
            } else if field.required {
                format!("      gen.writeStringField(\"{json}\", v.{ident});\n")
            } else {
                format!("      if (v.{ident} != null) {{\n        gen.writeStringField(\"{json}\", v.{ident});\n      }}\n")
            }
        }
        FieldType::Integer | FieldType::Number => {
            if field.required && !field.nullable {
                format!("      gen.writeNumberField(\"{json}\", v.{ident});\n")
            } else {
                format!("      if (v.{ident} != null) {{\n        gen.writeNumberField(\"{json}\", v.{ident});\n      }}\n")
            }
        }
        FieldType::Boolean => {
            if field.required && !field.nullable {
                format!("      gen.writeBooleanField(\"{json}\", v.{ident});\n")
            } else {
                format!("      if (v.{ident} != null) {{\n        gen.writeBooleanField(\"{json}\", v.{ident});\n      }}\n")
            }
        }
        FieldType::Array(inner) => {
            let _ = ir;
            let body = match inner.as_ref() {
                FieldType::String => format!("        for (String m : v.{ident}) {{\n          gen.writeString(m);\n        }}\n"),
                _ => format!("        for (Object m : v.{ident}) {{\n          sp.defaultSerializeValue(m, gen);\n        }}\n"),
            };
            format!("      if (v.{ident} != null) {{\n        gen.writeArrayFieldStart(\"{json}\");\n{body}        gen.writeEndArray();\n      }}\n")
        }
        FieldType::Ref(_) => {
            let inner = format!("        gen.writeFieldName(\"{json}\");\n        sp.defaultSerializeValue(v.{ident}, gen);\n");
            if field.required && !field.nullable {
                inner
            } else {
                format!("      if (v.{ident} != null) {{\n{inner}      }}\n")
            }
        }
    }
}

