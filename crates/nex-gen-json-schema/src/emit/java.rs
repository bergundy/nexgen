fn validation_exception(pkg: &str) -> String {
    format!(
        r#"{HEADER}
package {pkg};

import com.fasterxml.jackson.core.JsonParser;
import com.fasterxml.jackson.databind.JsonMappingException;
import java.util.Collections;
import java.util.List;
import org.jspecify.annotations.NullMarked;
import org.jspecify.annotations.Nullable;

/**
 * Aggregated validation failure thrown by a generated collecting
 * (de)serializer. Holds every {{@link Violation}} found while binding or
 * emitting a single payload.
 */
@NullMarked
public final class ValidationException extends JsonMappingException {{
  private final List<Violation> violations;

  public ValidationException(@Nullable JsonParser p, List<Violation> violations) {{
    super(p, summarize(violations));
    this.violations = Collections.unmodifiableList(violations);
  }}

  public List<Violation> getViolations() {{
    return violations;
  }}

  private static String summarize(List<Violation> violations) {{
    StringBuilder sb = new StringBuilder(violations.size() + " validation error(s):");
    for (Violation v : violations) {{
      sb.append("\n  ").append(v);
    }}
    return sb.toString();
  }}
}}
"#
    )
}

fn violation(pkg: &str) -> String {
    format!(
        r#"{HEADER}
package {pkg};

import org.jspecify.annotations.NullMarked;

/**
 * A single constraint violation, carrying the JSON-pointer-style path to the
 * offending member and a human-readable reason.
 */
@NullMarked
public final class Violation {{
  private final String path;
  private final String reason;

  public Violation(String path, String reason) {{
    this.path = path;
    this.reason = reason;
  }}

  public String getPath() {{
    return path;
  }}

  public String getReason() {{
    return reason;
  }}

  @Override
  public String toString() {{
    return path + ": " + reason;
  }}
}}
"#
    )
}

fn spec_numbers(pkg: &str) -> String {
    format!(
        r#"{HEADER}
package {pkg};

import com.fasterxml.jackson.databind.JsonNode;
import java.math.BigDecimal;
import java.util.List;
import org.jspecify.annotations.NullMarked;
import org.jspecify.annotations.Nullable;

/**
 * Spec-strict numeric helpers shared by every generated collecting
 * deserializer.
 */
@NullMarked
final class SpecNumbers {{
  private SpecNumbers() {{}}

  /** Cross-language integer cap: 2^53 - 1 (== JS Number.MAX_SAFE_INTEGER). */
  static final long CAP = 9007199254740991L;

  static @Nullable Long specLong(JsonNode n, String path, List<Violation> errs) {{
    if (!n.isNumber()) {{
      errs.add(new Violation(path, "expected integer"));
      return null;
    }}
    BigDecimal d = n.decimalValue();
    if (d.stripTrailingZeros().scale() > 0) {{
      errs.add(new Violation(path, "not an integer"));
      return null;
    }}
    if (d.abs().compareTo(BigDecimal.valueOf(CAP)) > 0) {{
      errs.add(new Violation(path, "integer exceeds +/-(2^53-1) cap"));
      return null;
    }}
    return d.longValueExact();
  }}
}}
"#
    )
}
