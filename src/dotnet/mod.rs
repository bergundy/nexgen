const GENERATED_HEADER: &str = "// <auto-generated />\n// Generated by nex-gen. DO NOT EDIT!";
const GENERATED_CODE_ATTRIBUTE: &str = "[GeneratedCode(\"nex-gen\", null)]";
const EXPERIMENTAL_WARNING: &str =
    "WARNING: This API is experimental and may change in the future.";

pub(crate) fn generate(symbols: &WitSymbols) -> Result<GeneratedFiles> {
    let support_fragments: Vec<SupportFragmentSpec> = symbols.fragments().cloned().collect();
    let support_fragments = support_fragments.as_slice();
    let support_namespace = dotnet_support_namespace(support_fragments)?;
    validate_dotnet_support_references(symbols, support_namespace.as_deref())?;
    let namespace = dotnet_namespace(symbols);
    let mut files = BTreeMap::<PathBuf, String>::new();
    files.insert(
        "Models.cs".into(),
        render_models_file(
            &namespace,
            symbols.enums().collect::<Vec<_>>().as_slice(),
            symbols.flags().collect::<Vec<_>>().as_slice(),
            symbols.variants().collect::<Vec<_>>().as_slice(),
            symbols.models().collect::<Vec<_>>().as_slice(),
            symbols,
            support_namespace.as_deref(),
        ),
    );
    files.insert(
        "Service.cs".into(),
        render_service_file(&namespace, symbols),
    );
    if symbols
        .services()
        .any(|service| !service.operations.is_empty())
    {
        files.insert(
            "Operations.cs".into(),
            render_operations_file(&namespace, symbols, support_namespace.as_deref()),
        );
    }
    if symbols
        .services()
        .any(|service| !service.resources.is_empty())
    {
        files.insert(
            "Resources.cs".into(),
            render_resources_file(&namespace, symbols),
        );
    }
    for fragment in support_fragments {
        files.insert(
            support_fragment_path(fragment)?,
            render_support_file(&fragment.contents),
        );
    }
    Ok(GeneratedFiles::directory(files))
}

fn dotnet_support_namespace(support_fragments: &[SupportFragmentSpec]) -> Result<Option<String>> {
    let mut namespace = None::<String>;
    for fragment in support_fragments {
        let Some(fragment_namespace) = fragment.namespace.as_deref() else {
            continue;
        };
        validate_dotnet_support_name(fragment_namespace).map_err(|reason| {
            Error::InvalidSupportNamespace {
                language: Language::Dotnet,
                namespace: fragment_namespace.to_string(),
                reason,
            }
        })?;
        if let Some(existing) = &namespace {
            if existing != fragment_namespace {
                return Err(Error::InvalidSupportNamespace {
                    language: Language::Dotnet,
                    namespace: fragment_namespace.to_string(),
                    reason: format!("conflicts with support namespace `{existing}`"),
                });
            }
        } else {
            namespace = Some(fragment_namespace.to_string());
        }
    }
    Ok(namespace)
}

fn validate_dotnet_support_references(
    symbols: &WitSymbols,
    support_namespace: Option<&str>,
) -> Result<()> {
    for model in symbols.models() {
        for sourced_field in &model.sourced_fields {
            if let Some(reference) = sourced_field.source_expr.strip_suffix("()") {
                validate_dotnet_support_reference(reference, support_namespace)?;
            }
            validate_dotnet_field_kind_support_references(&sourced_field.kind, support_namespace)?;
        }
        for field in &model.fields {
            if let Some(extractor) = field
                .function
                .as_ref()
                .and_then(|function| function.name_extractor.as_deref())
            {
                validate_dotnet_support_reference(extractor, support_namespace)?;
            }
            if let Some(extractor) = field
                .function
                .as_ref()
                .and_then(|function| function.call_extractor.as_deref())
            {
                validate_dotnet_support_reference(extractor, support_namespace)?;
            }
            if let Some(reference) = function_args_to_proto_converter(field) {
                validate_dotnet_support_reference(reference, support_namespace)?;
            }
            validate_dotnet_field_kind_support_references(&field.kind, support_namespace)?;
        }
    }
    Ok(())
}

fn validate_dotnet_field_kind_support_references(
    kind: &WitFieldKind,
    support_namespace: Option<&str>,
) -> Result<()> {
    match kind {
        WitFieldKind::Singular(value) | WitFieldKind::Repeated(value) => {
            validate_dotnet_value_support_references(value, support_namespace)
        }
        WitFieldKind::Map { key, value } => {
            validate_dotnet_value_support_references(key, support_namespace)?;
            validate_dotnet_value_support_references(value, support_namespace)
        }
    }
}

fn validate_dotnet_value_support_references(
    value: &WitValueType,
    support_namespace: Option<&str>,
) -> Result<()> {
    match value {
        WitValueType::Message(message) => {
            if let Some(reference) = dotnet_to_proto_converter(message) {
                validate_dotnet_support_reference(reference, support_namespace)?;
            }
        }
        WitValueType::External { fallback, .. } => {
            validate_dotnet_value_support_references(fallback, support_namespace)?;
        }
        WitValueType::Tuple(items) => {
            for item in items {
                validate_dotnet_value_support_references(item, support_namespace)?;
            }
        }
        WitValueType::Result { ok, err } => {
            if let Some(ok) = ok {
                validate_dotnet_value_support_references(ok, support_namespace)?;
            }
            if let Some(err) = err {
                validate_dotnet_value_support_references(err, support_namespace)?;
            }
        }
        _ => {}
    }
    Ok(())
}

fn validate_dotnet_support_reference(
    reference: &str,
    support_namespace: Option<&str>,
) -> Result<()> {
    let qualified = qualify_dotnet_support_reference(reference, support_namespace);
    validate_dotnet_support_name(&qualified).map_err(|reason| Error::InvalidSupportNamespace {
        language: Language::Dotnet,
        namespace: support_namespace.unwrap_or("").to_string(),
        reason: format!("invalid support reference `{reference}`: {reason}"),
    })
}

fn validate_dotnet_support_name(name: &str) -> std::result::Result<(), String> {
    if name.split('.').all(is_valid_csharp_identifier) {
        Ok(())
    } else {
        Err("must be a dotted C# identifier path".to_string())
    }
}

fn is_valid_csharp_identifier(name: &str) -> bool {
    let mut chars = name.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    (first == '_' || first.is_ascii_alphabetic())
        && chars.all(|character| character == '_' || character.is_ascii_alphanumeric())
}

fn qualify_dotnet_support_call(source_expr: &str, support_namespace: Option<&str>) -> String {
    if let Some(reference) = source_expr.strip_suffix("()") {
        format!(
            "{}()",
            qualify_dotnet_support_reference(reference, support_namespace)
        )
    } else {
        source_expr.to_string()
    }
}

fn qualify_dotnet_support_reference(reference: &str, support_namespace: Option<&str>) -> String {
    let Some(prefix) = support_namespace.filter(|prefix| !prefix.is_empty()) else {
        return reference.to_string();
    };
    if reference == prefix || reference.starts_with(&format!("{prefix}.")) {
        reference.to_string()
    } else {
        format!("{prefix}.{reference}")
    }
}

fn render_models_file(
    namespace: &str,
    enums: &[&WitEnum],
    flags: &[&WitFlags],
    variants: &[&crate::wit_symbols::WitVariant],
    models: &[&WitModel],
    symbols: &WitSymbols,
    support_namespace: Option<&str>,
) -> String {
    let needs_result = models.iter().any(|model| {
        model
            .fields
            .iter()
            .any(|field| field_kind_uses_result(&field.kind))
    });
    let mut imports = vec![
        "System",
        "System.CodeDom.Compiler",
        "System.Collections.Generic",
    ];
    if models
        .iter()
        .any(|model| model_uses_proto_extensions(model, symbols))
        && let Some(support_namespace) = support_namespace
    {
        imports.push(support_namespace);
    }
    let mut output = generated_file_prelude(namespace, &imports);
    if needs_result {
        render_result_helper(&mut output);
    }
    for enumeration in enums {
        render_enum(&mut output, enumeration);
    }
    for flag_set in flags {
        render_flags(&mut output, flag_set);
    }
    for variant in variants {
        render_variant(&mut output, variant);
    }
    for model in models {
        render_model(&mut output, model, symbols, support_namespace);
    }
    close_namespace(&mut output);
    output
}

fn render_service_file(namespace: &str, symbols: &WitSymbols) -> String {
    let mut output = generated_file_prelude(
        namespace,
        &["System", "System.CodeDom.Compiler", "NexusRpc"],
    );
    for service in symbols.services() {
        render_service_definition(&mut output, service, symbols);
    }
    close_namespace(&mut output);
    output
}

/// Lower a [`WitOperation`] into the core
/// [`Operation`](nex_gen_core::Operation) binding model, assigning per-service
/// I/O [`SymbolId`](nex_gen_core::SymbolId)s into `io_type_refs` from the
/// operation's resolved C# I/O type strings (`operation_raw_input_type` /
/// `operation_raw_return_type`).
///
/// Unlike the TypeScript / Python front-ends, .NET has no per-language rendered
/// model to hang the ids on — it renders straight from [`WitService`] — so it
/// builds the resolver table here. `input` is `Some` only when the operation
/// takes a request parameter (the core emits no parameter for `None`); the
/// symbol table is what [`operation_has_input`] consults to decide. `output` is
/// always registered (the raw return type already collapses the output-less case
/// to `"void"`).
fn lower_operation(
    operation: &WitOperation,
    symbols: &WitSymbols,
    io_type_refs: &mut Vec<String>,
) -> nex_gen_core::Operation {
    use nex_gen_core::{Name, Operation};

    let input = operation_has_input(operation, symbols).then(|| {
        push_io_ref(
            io_type_refs,
            operation_raw_input_type(symbols.op_input(operation.input)),
        )
    });
    let output = Some(push_io_ref(
        io_type_refs,
        operation_raw_return_type(operation, symbols),
    ));
    // The service binding only documents a return when the operation has an
    // output, matching `render_operation_summary_xml_doc`.
    let returns_doc = match symbols.op_output(operation.output) {
        WitOperationOutput::None => None,
        _ => dotnet_doc(&operation.return_doc).map(str::to_string),
    };
    Operation {
        name: Name::new(operation.name.as_str()),
        wire_name: operation.wire_name.to_string(),
        experimental: operation.experimental,
        input,
        output,
        docs: dotnet_doc(&operation.doc).map(str::to_string),
        returns_doc,
    }
}

fn render_service_definition(output: &mut String, service: &WitService, symbols: &WitSymbols) {
    use nex_gen_core::{Name, Service};

    // Build the frontend-agnostic service binding model, assigning per-service
    // I/O ids into `io_type_refs` (the resolver the core consults), then delegate
    // to the core `render_service` utility. The file prelude, `using` block, and
    // namespace wrapping stay in `render_service_file`.
    let mut io_type_refs: Vec<String> = Vec::new();
    let operations = service
        .operations
        .iter()
        .map(|operation| lower_operation(operation, symbols, &mut io_type_refs))
        .collect();
    let service_def = Service {
        name: Name::new(service.name.as_str()),
        wire_name: service.wire_name.to_string(),
        experimental: service.experimental,
        operations,
        // The .NET service interface renders no `<summary>` for the service
        // itself; only the experimental flag matters.
        docs: None,
    };
    output.push_str(&nex_gen_core::render::dotnet::render_service(
        &service_def,
        &io_type_refs,
    ));
}

fn render_operations_file(
    namespace: &str,
    symbols: &WitSymbols,
    support_namespace: Option<&str>,
) -> String {
    let imports = [
        "System",
        "System.CodeDom.Compiler",
        "System.Collections.Generic",
        "System.Linq",
        "System.Linq.Expressions",
        "System.Reflection",
        "System.Threading.Tasks",
        "Google.Protobuf.WellKnownTypes",
        "Temporalio.Converters",
        "Temporalio.Workflows",
    ];
    let mut output = generated_file_prelude(namespace, &imports);
    for service in symbols.services() {
        render_operations_class(&mut output, service, symbols, support_namespace);
    }
    close_namespace(&mut output);
    output
}

fn render_resources_file(namespace: &str, symbols: &WitSymbols) -> String {
    let mut output = generated_file_prelude(
        namespace,
        &[
            "System",
            "System.CodeDom.Compiler",
            "System.Collections.Generic",
            "System.Threading.Tasks",
        ],
    );
    for service in symbols.services() {
        for resource in &service.resources {
            render_resource(&mut output, service, resource, symbols);
        }
    }
    close_namespace(&mut output);
    output
}

fn generated_file_prelude(namespace: &str, imports: &[&str]) -> String {
    use std::collections::BTreeSet;

    use nex_gen_core::render::dotnet::{Import, render_imports};

    let mut output = String::new();
    output.push_str(GENERATED_HEADER);
    output.push_str("\n#nullable enable\n");
    output.push_str("#pragma warning disable CS1591\n\n");

    // Render the `using` block via the .NET import renderer: each namespace is a
    // whole-module `using X;`. Dedup here while preserving the dependency order
    // the front-end supplies (`render_imports` for .NET does not re-sort).
    let mut seen: BTreeSet<&str> = BTreeSet::new();
    let resolved: Vec<Import> = imports
        .iter()
        .filter(|module| seen.insert(**module))
        .map(|module| Import {
            module: (*module).to_string(),
        })
        .collect();
    let using_block = render_imports(&resolved);
    if !using_block.is_empty() {
        output.push_str(&using_block);
        output.push_str("\n\n");
    }

    output.push_str("namespace ");
    output.push_str(namespace);
    output.push_str("\n{\n\n");
    output
}

fn render_support_file(contents: &str) -> String {
    let mut output = String::new();
    if !contents.trim_start().starts_with("// <auto-generated") {
        output.push_str(GENERATED_HEADER);
        output.push('\n');
    }
    if !contents.contains("#nullable") {
        output.push_str("#nullable enable\n");
    }
    output.push_str(contents);
    output
}

fn close_namespace(output: &mut String) {
    indent_namespace_body(output);
    output.push_str("}\n");
}

fn indent_namespace_body(output: &mut String) {
    let Some(body_start) = output.find("\n{\n\n").map(|index| index + "\n{\n\n".len()) else {
        return;
    };
    let body = output[body_start..].to_string();
    output.truncate(body_start);
    for line in body.split_inclusive('\n') {
        if line == "\n" {
            output.push('\n');
        } else {
            output.push_str("    ");
            output.push_str(line);
        }
    }
}

fn dotnet_doc(spec: &crate::spec::LanguageStringSpec) -> Option<&str> {
    spec.for_language(Language::Dotnet)
}

fn render_operation_xml_doc(
    output: &mut String,
    indent: &str,
    operation: &WitOperation,
    symbols: &WitSymbols,
) {
    let return_doc = match symbols.op_output(operation.output) {
        WitOperationOutput::None => None,
        _ => dotnet_doc(&operation.return_doc),
    };
    let request_doc = symbols
        .model(&symbols.op_input(operation.input).info.full_name)
        .and_then(|model| dotnet_doc(model.generated_model.doc()));
    render_xml_doc(
        output,
        indent,
        dotnet_doc(&operation.doc),
        request_doc
            .map(|doc| vec![("request".to_string(), doc.to_string())])
            .unwrap_or_default(),
        return_doc,
        operation.experimental,
    );
}

fn render_field_xml_doc(output: &mut String, indent: &str, field: &WitField) {
    render_xml_summary(
        output,
        indent,
        field.doc.as_ref().and_then(dotnet_doc),
        false,
    );
}

fn render_xml_summary(
    output: &mut String,
    indent: &str,
    summary: Option<&str>,
    experimental: bool,
) {
    render_xml_doc(output, indent, summary, Vec::new(), None, experimental);
}

fn render_xml_doc(
    output: &mut String,
    indent: &str,
    summary: Option<&str>,
    params: Vec<(String, String)>,
    returns: Option<&str>,
    experimental: bool,
) {
    if summary.is_none() && params.is_empty() && returns.is_none() && !experimental {
        return;
    }
    if let Some(summary) = summary {
        output.push_str(indent);
        output.push_str("/// <summary>\n");
        render_xml_doc_text(output, indent, summary);
        output.push_str(indent);
        output.push_str("/// </summary>\n");
    }
    for (name, doc) in params {
        output.push_str(indent);
        output.push_str("/// <param name=\"");
        output.push_str(&name);
        output.push_str("\">");
        output.push_str(&xml_doc_escape(doc.trim()));
        output.push_str("</param>\n");
    }
    if let Some(returns) = returns {
        output.push_str(indent);
        output.push_str("/// <returns>");
        output.push_str(&xml_doc_escape(returns.trim()));
        output.push_str("</returns>\n");
    }
    if experimental {
        output.push_str(indent);
        output.push_str("/// <remarks>");
        output.push_str(EXPERIMENTAL_WARNING);
        output.push_str("</remarks>\n");
    }
}

fn render_xml_doc_text(output: &mut String, indent: &str, text: &str) {
    for line in text.trim().lines() {
        output.push_str(indent);
        output.push_str("/// ");
        output.push_str(&xml_doc_escape(line.trim()));
        output.push('\n');
    }
}

fn xml_doc_escape(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

fn render_operations_class(
    output: &mut String,
    service: &WitService,
    symbols: &WitSymbols,
    support_namespace: Option<&str>,
) {
    let service_type = format!("I{}", csharp_type_name(&service.name));
    for operation in &service.operations {
        render_operation_options_type(output, operation, symbols);
    }
    let explicit_operations_class = service
        .operations_class
        .for_language(Language::Dotnet)
        .is_some();
    if !explicit_operations_class {
        output.push_str(GENERATED_CODE_ATTRIBUTE);
        output.push('\n');
    }
    output.push_str("public static ");
    if explicit_operations_class {
        output.push_str("partial ");
    }
    output.push_str("class ");
    output.push_str(&dotnet_operations_class_name(service));
    output.push_str("\n{\n");
    output.push_str("    ");
    output.push_str(GENERATED_CODE_ATTRIBUTE);
    output.push('\n');
    output.push_str("    private const string ");
    output.push_str(&service_endpoint_constant_name(service));
    output.push_str(" = ");
    output.push_str(&csharp_string_literal(&service.endpoint));
    output.push_str(";\n\n");
    for operation in &service.operations {
        render_operation_extension(
            output,
            operation,
            symbols,
            &service_type,
            &service_endpoint_constant_name(service),
            support_namespace,
        );
    }
    output.push_str("}\n\n");
}

fn render_operation_extension(
    output: &mut String,
    operation: &WitOperation,
    symbols: &WitSymbols,
    service_type: &str,
    endpoint_constant_name: &str,
    support_namespace: Option<&str>,
) {
    let method_name = format!("{}Async", csharp_type_name(&operation.name));
    let input = symbols.op_input(operation.input);
    let raw_return = operation_raw_return_type(operation, symbols);
    let high_level_return = operation_return_type(operation, symbols);
    let has_input = operation_has_input(operation, symbols);
    let raw_input_type = operation_raw_input_type(input);
    let high_level_input_type = operation_input_type(input, symbols);

    if high_level_input_type == raw_input_type || !operation_requires_high_level_request(operation)
    {
        render_operation_request_extension(
            output,
            operation,
            service_type,
            &method_name,
            has_input,
            &raw_input_type,
            &raw_return,
            &high_level_return,
            RequestArgumentKind::Raw,
            endpoint_constant_name,
            symbols,
        );
    }

    if has_input && high_level_input_type != raw_input_type {
        render_operation_request_extension(
            output,
            operation,
            service_type,
            &method_name,
            has_input,
            &high_level_input_type,
            &raw_return,
            &high_level_return,
            RequestArgumentKind::HighLevel,
            endpoint_constant_name,
            symbols,
        );
    }

    if let Some(model) = symbols.model(&input.info.full_name)
        && operation_has_flattened_convenience(operation, model, symbols)
    {
        render_operation_flattened_extension(
            output,
            operation,
            &method_name,
            model,
            &raw_return,
            &high_level_return,
            symbols,
            support_namespace,
        );
    }
}

#[derive(Clone, Copy)]
enum RequestArgumentKind {
    Raw,
    HighLevel,
}

fn render_operation_request_extension(
    output: &mut String,
    operation: &WitOperation,
    service_type: &str,
    method_name: &str,
    has_input: bool,
    input_type: &str,
    raw_return: &str,
    high_level_return: &str,
    request_kind: RequestArgumentKind,
    endpoint_constant_name: &str,
    symbols: &WitSymbols,
) {
    render_operation_xml_doc(output, "    ", operation, symbols);
    output.push_str("    ");
    output.push_str(GENERATED_CODE_ATTRIBUTE);
    output.push('\n');
    output.push_str("    ");
    output.push_str(operation_request_method_access(
        operation,
        request_kind,
        symbols,
    ));
    output.push_str(" static ");
    if raw_return == "void" {
        output.push_str("async Task ");
    } else {
        output.push_str("async Task<");
        output.push_str(high_level_return);
        output.push_str("> ");
    }
    output.push_str(&method_name);
    output.push('(');
    if has_input {
        output.push_str(&input_type);
        output.push_str(" request");
    }
    output.push_str(")\n    {\n");
    output.push_str("        var client = Workflow.CreateNexusWorkflowClient<");
    output.push_str(service_type);
    output.push_str(">(");
    output.push_str(endpoint_constant_name);
    output.push_str(");\n");
    if matches!(request_kind, RequestArgumentKind::HighLevel) {
        output.push_str("        var protoRequest = request.ToProto();\n");
    }
    if raw_return == "void" {
        output.push_str("        await client.ExecuteNexusOperationAsync(svc => svc.");
    } else {
        output.push_str("        var result = await client.ExecuteNexusOperationAsync<");
        output.push_str(&raw_return);
        output.push_str(">(svc => svc.");
    }
    output.push_str(&csharp_type_name(&operation.name));
    output.push('(');
    if has_input {
        if matches!(request_kind, RequestArgumentKind::HighLevel) {
            output.push_str("protoRequest");
        } else {
            output.push_str("request");
        }
    }
    output.push(')');
    output.push_str(").ConfigureAwait(true);\n");
    if raw_return == "void" {
        output.push_str("    }\n\n");
        return;
    }
    if operation.output_transform.is_some() || operation.output_resource_return.is_some() {
        output.push_str("        return ");
        output.push_str(&operation_transform_expression(
            operation,
            "request",
            "protoRequest",
            "result",
            symbols,
        ));
        output.push_str(";\n");
    } else {
        output.push_str("        return result;\n");
    }
    output.push_str("    }\n\n");
}

fn operation_request_method_access(
    operation: &WitOperation,
    request_kind: RequestArgumentKind,
    symbols: &WitSymbols,
) -> &'static str {
    let input = symbols.op_input(operation.input);
    let raw_input_type = operation_raw_input_type(input);
    let high_level_input_type = operation_input_type(input, symbols);
    if (matches!(request_kind, RequestArgumentKind::HighLevel)
        || high_level_input_type == raw_input_type)
        && symbols
            .model(&input.info.full_name)
            .is_some_and(|model| operation_has_flattened_convenience(operation, model, symbols))
    {
        "private"
    } else {
        "public"
    }
}

fn operation_requires_high_level_request(operation: &WitOperation) -> bool {
    operation.output_transform.is_some() || operation.output_resource_return.is_some()
}

fn operation_has_flattened_convenience(
    _operation: &WitOperation,
    model: &WitModel,
    _symbols: &WitSymbols,
) -> bool {
    !model.fields.is_empty() && model_function_fields_flattenable(model)
}

fn model_function_fields_flattenable(model: &WitModel) -> bool {
    let mut has_function_fields = false;
    for field in &model.fields {
        if let Some(function) = &field.function {
            has_function_fields = true;
            if function.name_extractor.is_none() || function.call_extractor.is_none() {
                return false;
            }
        }
    }
    !has_function_fields || model_has_extractable_function_fields(model)
}

fn render_operation_flattened_overload(
    output: &mut String,
    operation: &WitOperation,
    method_name: &str,
    model: &WitModel,
    raw_return: &str,
    high_level_return: &str,
    symbols: &WitSymbols,
    overload: &FlattenedOverload,
    support_namespace: Option<&str>,
) {
    render_flattened_method_signature(
        output,
        operation,
        method_name,
        raw_return,
        high_level_return,
        model,
        symbols,
        overload,
    );
    render_flattened_method_body(
        output,
        operation,
        model,
        symbols,
        overload,
        support_namespace,
    );
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum FlattenedFunctionMode {
    String,
    Expression,
}

struct FlattenedOverload {
    function_modes: Vec<(String, FlattenedFunctionMode)>,
}

impl FlattenedOverload {
    fn function_mode(&self, field: &WitField) -> FlattenedFunctionMode {
        self.function_modes
            .iter()
            .find_map(|(field_name, mode)| (field_name == &field.proto_name).then_some(*mode))
            .unwrap_or(FlattenedFunctionMode::String)
    }

    fn has_expression_functions(&self) -> bool {
        self.function_modes
            .iter()
            .any(|(_, mode)| matches!(mode, FlattenedFunctionMode::Expression))
    }
}

fn flattened_overloads(model: &WitModel) -> Vec<FlattenedOverload> {
    let function_fields = model
        .fields
        .iter()
        .filter(|field| field.function.is_some())
        .collect::<Vec<_>>();
    if function_fields.is_empty() {
        return vec![FlattenedOverload {
            function_modes: Vec::new(),
        }];
    }
    (0..(1usize << function_fields.len()))
        .map(|mask| FlattenedOverload {
            function_modes: function_fields
                .iter()
                .enumerate()
                .map(|(index, field)| {
                    let mode = if mask & (1usize << index) == 0 {
                        FlattenedFunctionMode::String
                    } else {
                        FlattenedFunctionMode::Expression
                    };
                    (field.proto_name.clone(), mode)
                })
                .collect(),
        })
        .collect()
}

fn render_flattened_method_signature(
    output: &mut String,
    operation: &WitOperation,
    method_name: &str,
    raw_return: &str,
    high_level_return: &str,
    model: &WitModel,
    symbols: &WitSymbols,
    overload: &FlattenedOverload,
) {
    render_operation_flattened_xml_doc(output, "    ", operation, model, symbols, overload);
    output.push_str("    ");
    output.push_str(GENERATED_CODE_ATTRIBUTE);
    output.push('\n');
    output.push_str("    public static ");
    if raw_return == "void" {
        output.push_str("Task ");
    } else {
        output.push_str("Task<");
        output.push_str(high_level_return);
        output.push_str("> ");
    }
    output.push_str(method_name);
    render_flattened_generic_parameters(output, model, overload);
    output.push('(');
    let mut has_parameters = false;
    render_flattened_parameters(output, model, symbols, overload, &mut has_parameters);
    if model_has_options_fields(model, symbols) {
        render_parameter_separator(output, &mut has_parameters);
        output.push_str(&operation_options_type_name(operation));
        if model_options_required(model, symbols) {
            output.push_str(" options");
        } else {
            output.push_str("? options = null");
        }
    }
    output.push_str(")\n    {\n");
}

fn render_operation_flattened_xml_doc(
    output: &mut String,
    indent: &str,
    operation: &WitOperation,
    model: &WitModel,
    symbols: &WitSymbols,
    overload: &FlattenedOverload,
) {
    let return_doc = match symbols.op_output(operation.output) {
        WitOperationOutput::None => None,
        _ => dotnet_doc(&operation.return_doc),
    };
    render_xml_doc(
        output,
        indent,
        dotnet_doc(&operation.doc),
        flattened_method_parameter_docs(model, symbols, overload),
        return_doc,
        operation.experimental,
    );
}

fn flattened_method_parameter_docs(
    model: &WitModel,
    symbols: &WitSymbols,
    overload: &FlattenedOverload,
) -> Vec<(String, String)> {
    let mut params = Vec::new();
    for field in &model.fields {
        if field.function.is_none() {
            continue;
        }
        if let Some(nested_model) = flattened_nested_model(field, symbols) {
            for nested_field in &nested_model.fields {
                if nested_field.function.is_none() {
                    continue;
                }
                push_field_parameter_doc(&mut params, nested_field);
            }
            continue;
        }
        push_field_parameter_doc(&mut params, field);
        if matches!(overload.function_mode(field), FlattenedFunctionMode::String) {
            push_function_args_parameter_docs(&mut params, model, field);
        }
    }
    if model_has_options_fields(model, symbols) {
        params.push((
            "options".to_string(),
            dotnet_doc(model.generated_model.doc())
                .map(str::to_string)
                .unwrap_or_else(|| "Options for the operation.".to_string()),
        ));
    }
    params
}

fn push_field_parameter_doc(params: &mut Vec<(String, String)>, field: &WitField) {
    params.push((
        csharp_parameter_name(&field.authored_name),
        field
            .doc
            .as_ref()
            .and_then(dotnet_doc)
            .map(str::to_string)
            .unwrap_or_else(|| fallback_parameter_doc(field)),
    ));
}

fn fallback_parameter_doc(field: &WitField) -> String {
    format!("The {} value.", csharp_parameter_name(&field.authored_name))
}

fn push_function_args_parameter_docs(
    params: &mut Vec<(String, String)>,
    model: &WitModel,
    function_field: &WitField,
) {
    let Some(function) = &function_field.function else {
        return;
    };
    for arg_field_name in &function.arg_fields {
        let Some(arg_field) = model
            .fields
            .iter()
            .find(|field| &field.proto_name == arg_field_name)
        else {
            continue;
        };
        push_field_parameter_doc(params, arg_field);
    }
}

fn render_flattened_parameters(
    output: &mut String,
    model: &WitModel,
    symbols: &WitSymbols,
    overload: &FlattenedOverload,
    has_parameters: &mut bool,
) {
    for field in &model.fields {
        if field.function.is_none() {
            continue;
        }
        if let Some(nested_model) = flattened_nested_model(field, symbols) {
            for nested_field in &nested_model.fields {
                if nested_field.function.is_none() {
                    continue;
                }
                let nested_required = field.required && nested_field.required;
                render_parameter_separator(output, has_parameters);
                output.push_str(&flattened_nested_parameter_type(
                    nested_model,
                    nested_field,
                    symbols,
                ));
                output.push(' ');
                output.push_str(&csharp_parameter_name(&nested_field.authored_name));
                if !nested_required {
                    output.push_str(" = null");
                }
            }
            continue;
        }
        render_parameter_separator(output, has_parameters);
        output.push_str(&flattened_parameter_type(
            model,
            field,
            symbols,
            overload.function_mode(field),
        ));
        output.push(' ');
        output.push_str(&csharp_parameter_name(&field.authored_name));
        if !field.required {
            output.push_str(" = null");
        }
        if matches!(overload.function_mode(field), FlattenedFunctionMode::String) {
            render_function_args_parameters(output, model, field, symbols, has_parameters);
        }
    }
}

fn render_function_args_parameters(
    output: &mut String,
    model: &WitModel,
    function_field: &WitField,
    symbols: &WitSymbols,
    has_parameters: &mut bool,
) {
    let Some(function) = &function_field.function else {
        return;
    };
    for arg_field_name in &function.arg_fields {
        let Some(arg_field) = model
            .fields
            .iter()
            .find(|field| &field.proto_name == arg_field_name)
        else {
            continue;
        };
        render_parameter_separator(output, has_parameters);
        output.push_str(&flattened_parameter_type(
            model,
            arg_field,
            symbols,
            FlattenedFunctionMode::String,
        ));
        output.push(' ');
        output.push_str(&csharp_parameter_name(&arg_field.authored_name));
    }
}

fn render_parameter_separator(output: &mut String, has_parameters: &mut bool) {
    if *has_parameters {
        output.push_str(", ");
    } else {
        *has_parameters = true;
    }
}

fn render_flattened_generic_parameters(
    output: &mut String,
    model: &WitModel,
    overload: &FlattenedOverload,
) {
    if !overload.has_expression_functions() {
        return;
    }
    let mut generics = vec!["TWorkflow".to_string()];
    if model.fields.iter().any(|field| {
        matches!(
            overload.function_mode(field),
            FlattenedFunctionMode::Expression
        ) && field
            .function
            .as_ref()
            .is_some_and(function_has_result_type_parameter)
    }) {
        generics.push("TResult".to_string());
    }
    output.push('<');
    output.push_str(&generics.join(", "));
    output.push('>');
}

fn render_flattened_method_body(
    output: &mut String,
    operation: &WitOperation,
    model: &WitModel,
    symbols: &WitSymbols,
    overload: &FlattenedOverload,
    support_namespace: Option<&str>,
) {
    let options_required = model_options_required(model, symbols);
    for field in &model.fields {
        if field.function.is_some()
            && matches!(
                overload.function_mode(field),
                FlattenedFunctionMode::Expression
            )
        {
            output.push_str("        var (");
            output.push_str(&csharp_parameter_name(&format!(
                "{}Method",
                field.authored_name
            )));
            output.push_str(", ");
            output.push_str(&csharp_parameter_name(&format!(
                "{}Args",
                field.authored_name
            )));
            output.push_str(") = ");
            let extractor = field
                .function
                .as_ref()
                .and_then(|function| function.call_extractor.as_deref())
                .expect("expression overloads require function call extractors");
            let extractor = qualify_dotnet_support_reference(extractor, support_namespace);
            output.push_str(&extractor);
            output.push('(');
            output.push_str(&csharp_parameter_name(&field.authored_name));
            output.push_str(");\n");
        }
    }
    output.push_str("        var request = new ");
    output.push_str(&csharp_type_name(&model.name));
    let field_exprs = model
        .fields
        .iter()
        .map(|field| {
            (
                field,
                flattened_request_field_expr(
                    field,
                    model,
                    symbols,
                    overload,
                    support_namespace,
                    options_required,
                ),
            )
        })
        .collect::<Vec<_>>();
    output.push('(');
    output.push_str(
        &field_exprs
            .iter()
            .filter(|(field, _)| field.required)
            .map(|(_, expr)| expr.as_str())
            .collect::<Vec<_>>()
            .join(", "),
    );
    output.push(')');
    let optional_field_exprs = field_exprs
        .iter()
        .filter(|(field, _)| !field.required)
        .collect::<Vec<_>>();
    if optional_field_exprs.is_empty() {
        output.push_str(";\n");
    } else {
        output.push_str("\n        {\n");
        for (field, expr) in optional_field_exprs {
            output.push_str("            ");
            output.push_str(&field_property_name(field));
            output.push_str(" = ");
            output.push_str(expr);
            output.push_str(",\n");
        }
        output.push_str("        };\n");
    }
    output.push_str("        return ");
    output.push_str(&csharp_type_name(&operation.name));
    output.push_str("Async(request);\n");
    output.push_str("    }\n\n");
}

fn flattened_request_field_expr(
    field: &WitField,
    model: &WitModel,
    symbols: &WitSymbols,
    overload: &FlattenedOverload,
    support_namespace: Option<&str>,
    options_required: bool,
) -> String {
    if let Some(nested_model) = flattened_nested_model(field, symbols) {
        nested_model_init_expr(field, nested_model, options_required)
    } else if field.function.is_some()
        && matches!(
            overload.function_mode(field),
            FlattenedFunctionMode::Expression
        )
    {
        function_name_expression(field, support_namespace)
    } else if field.function_args
        && let Some(mode) = function_args_field_mode(model, field, overload)
    {
        if matches!(mode, FlattenedFunctionMode::Expression) {
            let function_field = model
                .fields
                .iter()
                .find(|candidate| {
                    candidate
                        .function
                        .as_ref()
                        .is_some_and(|function| function.arg_fields.contains(&field.proto_name))
                })
                .expect("function args field should have a function field");
            csharp_parameter_name(&format!("{}Args", function_field.authored_name))
        } else {
            csharp_parameter_name(&field.authored_name)
        }
    } else if field.function.is_none() {
        option_field_expr(field, options_required)
    } else {
        csharp_parameter_name(&field.authored_name)
    }
}

fn function_name_expression(field: &WitField, support_namespace: Option<&str>) -> String {
    let method_var = csharp_parameter_name(&format!("{}Method", field.authored_name));
    let extractor = field
        .function
        .as_ref()
        .and_then(|function| function.name_extractor.as_deref())
        .expect("expression overloads require function name extractors");
    let extractor = qualify_dotnet_support_reference(extractor, support_namespace);
    format!("{extractor}({method_var})")
}

fn function_args_field_mode(
    model: &WitModel,
    args_field: &WitField,
    overload: &FlattenedOverload,
) -> Option<FlattenedFunctionMode> {
    model
        .fields
        .iter()
        .find(|candidate| {
            candidate
                .function
                .as_ref()
                .is_some_and(|function| function.arg_fields.contains(&args_field.proto_name))
        })
        .map(|function_field| overload.function_mode(function_field))
}

fn flattened_nested_model<'a>(field: &WitField, symbols: &WitSymbols<'a>) -> Option<&'a WitModel> {
    let WitFieldKind::Singular(WitValueType::Message(message)) = &field.kind else {
        return None;
    };
    let nested_model = symbols.model(&message.info.full_name)?;
    nested_model.flatten_in_api.then_some(nested_model)
}

fn render_operation_options_type(
    output: &mut String,
    operation: &WitOperation,
    symbols: &WitSymbols,
) {
    let Some(model) = symbols.model(&symbols.op_input(operation.input).info.full_name) else {
        return;
    };
    if !operation_has_flattened_convenience(operation, model, symbols)
        || !model_has_options_fields(model, symbols)
    {
        return;
    }

    render_xml_summary(
        output,
        "",
        dotnet_doc(&operation.doc),
        operation.experimental,
    );
    output.push_str(GENERATED_CODE_ATTRIBUTE);
    output.push('\n');
    output.push_str("public class ");
    let options_type_name = operation_options_type_name(operation);
    output.push_str(&options_type_name);
    output.push_str("\n{\n");
    let mut option_fields = Vec::<(&WitField, String, bool)>::new();
    for field in &model.fields {
        if let Some(nested_model) = flattened_nested_model(field, symbols) {
            for nested_field in &nested_model.fields {
                if !field_is_options_field(nested_field) {
                    continue;
                }
                let field_type =
                    flattened_nested_parameter_type(nested_model, nested_field, symbols);
                option_fields.push((
                    nested_field,
                    field_type,
                    field.required && nested_field.required,
                ));
            }
            continue;
        }
        if !field_is_options_field(field) {
            continue;
        }
        let field_type =
            flattened_parameter_type(model, field, symbols, FlattenedFunctionMode::String);
        option_fields.push((field, field_type, field.required));
    }
    render_operation_options_constructor(output, &options_type_name, &option_fields);
    for (field, field_type, _) in option_fields {
        render_field_xml_doc(output, "    ", field);
        output.push_str("    public ");
        output.push_str(&field_type);
        output.push(' ');
        output.push_str(&field_property_name(field));
        output.push_str(" { get; set; }\n");
    }
    output.push_str("}\n\n");
}

fn render_operation_options_constructor(
    output: &mut String,
    type_name: &str,
    option_fields: &[(&WitField, String, bool)],
) {
    let required_fields = option_fields
        .iter()
        .filter(|(_, _, required)| *required)
        .collect::<Vec<_>>();
    if required_fields.is_empty() {
        return;
    }
    output.push_str("    public ");
    output.push_str(type_name);
    output.push('(');
    for (index, (field, field_type, _)) in required_fields.iter().enumerate() {
        if index > 0 {
            output.push_str(", ");
        }
        output.push_str(field_type);
        output.push(' ');
        output.push_str(&csharp_parameter_name(&field.authored_name));
    }
    output.push_str(")\n    {\n");
    for (field, _, _) in required_fields {
        output.push_str("        ");
        output.push_str(&field_property_name(field));
        output.push_str(" = ");
        output.push_str(&csharp_parameter_name(&field.authored_name));
        output.push_str(";\n");
    }
    output.push_str("    }\n\n");
}

fn operation_options_type_name(operation: &WitOperation) -> String {
    csharp_type_name(&format!("{}Options", operation.name))
}

fn model_has_options_fields(model: &WitModel, symbols: &WitSymbols) -> bool {
    model.fields.iter().any(|field| {
        if let Some(nested_model) = flattened_nested_model(field, symbols) {
            nested_model.fields.iter().any(field_is_options_field)
        } else {
            field_is_options_field(field)
        }
    })
}

fn model_options_required(model: &WitModel, symbols: &WitSymbols) -> bool {
    model.fields.iter().any(|field| {
        if let Some(nested_model) = flattened_nested_model(field, symbols) {
            field.required
                && nested_model.fields.iter().any(|nested_field| {
                    nested_field.required && field_is_options_field(nested_field)
                })
        } else {
            field.required && field_is_options_field(field)
        }
    })
}

fn field_is_options_field(field: &WitField) -> bool {
    field.function.is_none() && !field.function_args
}

fn nested_model_init_expr(field: &WitField, model: &WitModel, options_required: bool) -> String {
    let option_fields = model
        .fields
        .iter()
        .filter(|nested_field| field_is_options_field(nested_field))
        .collect::<Vec<_>>();
    let checks = option_fields
        .iter()
        .map(|nested_field| {
            format!(
                "{} != null",
                option_nested_field_expr(field, nested_field, options_required)
            )
        })
        .collect::<Vec<_>>()
        .join(" || ");
    let init_expr = model_init_expr(
        &csharp_type_name(&model.name),
        option_fields
            .into_iter()
            .map(|nested_field| {
                (
                    nested_field,
                    option_nested_field_expr(field, nested_field, options_required),
                )
            })
            .collect(),
    );
    if field.required {
        init_expr
    } else {
        format!("{checks} ? {init_expr} : null")
    }
}

fn model_init_expr(type_name: &str, field_exprs: Vec<(&WitField, String)>) -> String {
    let constructor_args = field_exprs
        .iter()
        .filter(|(field, _)| field.required)
        .map(|(_, expr)| expr.as_str())
        .collect::<Vec<_>>()
        .join(", ");
    let assignments = field_exprs
        .iter()
        .filter(|(field, _)| !field.required)
        .map(|(field, expr)| format!("{} = {}", field_property_name(field), expr))
        .collect::<Vec<_>>()
        .join(", ");
    let mut expr = format!("new {type_name}({constructor_args})");
    if !assignments.is_empty() {
        expr.push_str(" { ");
        expr.push_str(&assignments);
        expr.push_str(" }");
    }
    expr
}

fn option_field_expr(field: &WitField, options_required: bool) -> String {
    if options_required || field.required {
        format!("options.{}", field_property_name(field))
    } else {
        format!("options?.{}", field_property_name(field))
    }
}

fn option_nested_field_expr(
    field: &WitField,
    nested_field: &WitField,
    options_required: bool,
) -> String {
    if options_required || (field.required && nested_field.required) {
        format!("options.{}", field_property_name(nested_field))
    } else {
        format!("options?.{}", field_property_name(nested_field))
    }
}

fn function_has_result_type_parameter(function: &FunctionFieldSpec) -> bool {
    function.result_type_parameter.is_some()
}

fn render_operation_flattened_extension(
    output: &mut String,
    operation: &WitOperation,
    method_name: &str,
    model: &WitModel,
    raw_return: &str,
    high_level_return: &str,
    symbols: &WitSymbols,
    support_namespace: Option<&str>,
) {
    for overload in flattened_overloads(model) {
        render_operation_flattened_overload(
            output,
            operation,
            method_name,
            model,
            raw_return,
            high_level_return,
            symbols,
            &overload,
            support_namespace,
        );
    }
}

fn model_has_extractable_function_fields(model: &WitModel) -> bool {
    let mut has_function_fields = false;
    for field in &model.fields {
        if let Some(function) = &field.function {
            has_function_fields = true;
            if function.name_extractor.is_none() {
                return false;
            }
        }
    }
    has_function_fields
}

