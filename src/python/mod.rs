fn required_from_proto_setup_lines(
    model_name: &str,
    attr_name: &str,
    proto_name: &str,
    field: &PlannedField,
    resolved_type: &ResolvedFieldType,
) -> Vec<String> {
    let error = python_string_literal(&required_field_error(model_name, attr_name));
    let proto_expr = format!("proto.{proto_name}");
    let mut lines = Vec::new();
    if field.has_presence {
        lines.push(format!("if not proto.HasField(\"{proto_name}\"):"));
        lines.push(format!("    raise ValueError({error})"));
    } else if matches!(
        &field.kind,
        PlannedFieldKind::Singular(PlannedValueType::Scalar(
            PlannedScalarType::String | PlannedScalarType::Bytes
        ))
    ) {
        lines.push(format!("if not proto.{proto_name}:"));
        lines.push(format!("    raise ValueError({error})"));
    }
    lines.push(format!(
        "{attr_name} = {}",
        required_from_proto_value_expr(resolved_type, &proto_expr)
    ));
    lines
}

fn required_from_proto_value_expr(resolved_type: &ResolvedFieldType, proto_expr: &str) -> String {
    match resolved_type.kind {
        ResolvedFieldKind::Message => resolved_type
            .message_conversion
            .as_ref()
            .expect("message conversion should be present")
            .from_proto_expr(proto_expr),
        ResolvedFieldKind::Enum => enum_from_proto_expr(resolved_type, proto_expr),
        _ => proto_expr.to_string(),
    }
}

fn required_to_proto_lines(
    model_name: &str,
    attr_name: &str,
    proto_name: &str,
    resolved_type: &ResolvedFieldType,
) -> Vec<String> {
    let error = python_string_literal(&required_field_error(model_name, attr_name));
    let value_name = format!("{attr_name}_value");
    let typed_value_expr = format!("typing.cast({}, {value_name})", resolved_type.annotation);
    let mut lines = vec![
        format!("{value_name}: object | None = getattr(self, \"{attr_name}\", None)"),
        format!("if {value_name} is None:"),
        format!("    raise ValueError({error})"),
    ];
    match resolved_type.kind {
        ResolvedFieldKind::Message => lines.push(format!(
            "message.{proto_name}.CopyFrom({})",
            resolved_type
                .message_conversion
                .as_ref()
                .expect("message conversion should be present")
                .to_proto_expr(&typed_value_expr)
        )),
        ResolvedFieldKind::Enum => lines.push(format!(
            "message.{proto_name} = {}",
            enum_to_proto_expr(resolved_type, &typed_value_expr)
        )),
        _ => lines.push(format!("message.{proto_name} = {typed_value_expr}")),
    }
    lines
}

