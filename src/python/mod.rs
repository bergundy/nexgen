fn resource_bound_operations<'a>(
    service: &'a RenderedService<'a>,
    resource: &'a PlannedResource,
) -> Vec<ResourceBoundOperation<'a>> {
    resource
        .methods
        .iter()
        .filter_map(|method| match &method.binding {
            PlannedResourceMethodBindingSpec::Operation { operation_name, .. } => {
                Some(ResourceBoundOperation {
                    operation: service
                        .operations
                        .iter()
                        .find(|operation| operation.name == operation_name)
                        .expect("bound resource operation should exist on the service"),
                })
            }
            PlannedResourceMethodBindingSpec::Stub => None,
        })
        .collect()
}

fn render_resource_module_file(
    service: &RenderedService<'_>,
    resource: &PlannedResource,
    bound_operations: &[ResourceBoundOperation<'_>],
    model_names: &[String],
    resource_names: &[String],
    support_names: &[String],
) -> String {
    let module_imports = bound_operations
        .iter()
        .flat_map(|bound_operation| {
            [
                bound_operation.operation.input_module_path.clone(),
                bound_operation.operation.output_module_path.clone(),
            ]
        })
        .collect::<BTreeSet<_>>();

    let mut body = String::new();
    if bound_operations.iter().any(|bound_operation| {
        bound_operation
            .operation
            .unpacked_input
            .as_ref()
            .is_some_and(|unpacked_input| !unpacked_input.functions.is_empty())
    }) {
        render_function_args_normalizer(&mut body);
        body.push_str("\n\n");
    }
    let function_fields = bound_operations
        .iter()
        .filter_map(|bound_operation| bound_operation.operation.unpacked_input.as_ref())
        .flat_map(|unpacked_input| unpacked_input.functions.iter().cloned())
        .collect::<Vec<_>>();
    if !function_fields.is_empty() {
        render_function_type_parameter_definitions(&mut body, &function_fields);
        body.push_str("\n\n");
    }
    render_resource(&mut body, resource, bound_operations);
    if !bound_operations.is_empty() {
        body.push_str("\n\n");
        for (index, bound_operation) in bound_operations.iter().enumerate() {
            render_operation_functions(&mut body, service, bound_operation.operation);
            if index + 1 != bound_operations.len() {
                body.push_str("\n\n");
            }
        }
    }

    let mut output = String::new();
    render_generated_file_header(&mut output);
    output.push('\n');
    let wrote_imports = render_optional_python_imports(&mut output, &body, &module_imports);
    if wrote_imports {
        output.push('\n');
    }
    let service_import = vec![service.name.to_string()];
    render_named_python_import(&mut output, "..service", &service_import);
    let used_model_names = used_python_symbol_imports(&body, model_names);
    if !used_model_names.is_empty() {
        render_named_python_import(&mut output, "..models", &used_model_names);
    }
    let used_resource_names = used_python_symbol_imports(&body, resource_names)
        .into_iter()
        .filter(|name| name != &resource.type_name)
        .collect::<Vec<_>>();
    if !used_resource_names.is_empty() {
        render_named_python_import(&mut output, ".", &used_resource_names);
    }
    let used_support_names = used_python_symbol_imports(&body, support_names);
    if !used_support_names.is_empty() {
        render_named_python_import(&mut output, ".._support", &used_support_names);
    }
    if !body.is_empty() {
        output.push('\n');
        output.push('\n');
        output.push_str(&body);
    }
    output
}

fn render_service_module(services: &[RenderedService<'_>]) -> String {
    let mut module_imports = BTreeSet::new();
    for service in services {
        for operation in &service.operations {
            module_imports.insert(operation.input_module_path.clone());
            module_imports.insert(operation.output_module_path.clone());
        }
    }

    let mut output = String::new();
    render_generated_file_header(&mut output);
    output.push('\n');
    output.push_str("from nexusrpc import Operation, service\n");
    if !module_imports.is_empty() {
        output.push('\n');
        render_python_module_imports(&mut output, &module_imports);
    }
    if !services.is_empty() {
        output.push_str("\n\n");
        for (index, service) in services.iter().enumerate() {
            render_service_definition(&mut output, service);
            if index + 1 != services.len() {
                output.push_str("\n\n");
            }
        }
    }

    output
}

fn render_operation_module(
    service: &RenderedService<'_>,
    operation: &RenderedOperation<'_>,
    model_names: &[String],
    resource_names: &[String],
    support_names: &[String],
) -> String {
    let mut module_imports = BTreeSet::new();
    module_imports.insert(operation.input_module_path.clone());
    module_imports.insert(operation.output_module_path.clone());

    let mut body = String::new();
    if operation
        .unpacked_input
        .as_ref()
        .is_some_and(|unpacked_input| !unpacked_input.functions.is_empty())
    {
        render_function_args_normalizer(&mut body);
        body.push_str("\n\n");
    }
    if let Some(unpacked_input) = &operation.unpacked_input
        && !unpacked_input.functions.is_empty()
    {
        render_function_type_parameter_definitions(&mut body, &unpacked_input.functions);
        body.push_str("\n\n");
    }
    render_operation_functions(&mut body, service, operation);

    let mut output = String::new();
    render_generated_file_header(&mut output);
    output.push('\n');
    let wrote_imports = render_optional_python_imports(&mut output, &body, &module_imports);
    if wrote_imports {
        output.push('\n');
    }
    output.push_str("from ");
    output.push_str("..");
    output.push_str("service import ");
    output.push_str(service.name);
    output.push('\n');
    let used_model_names = used_python_symbol_imports(&body, model_names);
    render_named_python_import(&mut output, "..models", &used_model_names);
    let used_resource_names = used_python_symbol_imports(&body, resource_names);
    if !used_resource_names.is_empty() {
        render_named_python_import(&mut output, ".._resources", &used_resource_names);
    }
    let used_support_names = used_python_symbol_imports(&body, support_names);
    if !used_support_names.is_empty() {
        render_named_python_import(&mut output, ".._support", &used_support_names);
    }
    output.push('\n');
    output.push('\n');
    output.push_str(&body);
    output
}

