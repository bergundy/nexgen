#[derive(Debug)]
struct PythonReference {
    module_path: String,
    type_ref: String,
}

fn message_python_ref(type_info: &PlannedTypeInfo) -> Option<PythonReference> {
    let module_path =
        python_module_path_for_file_name(type_info.file_name.as_deref(), &type_info.package)?;
    let relative_name = relative_descriptor_name(&type_info.full_name, &type_info.package);
    Some(PythonReference {
        type_ref: format!("{module_path}.{relative_name}"),
        module_path,
    })
}

fn enum_python_ref(type_info: &PlannedTypeInfo) -> Option<PythonReference> {
    let module_path =
        python_module_path_for_file_name(type_info.file_name.as_deref(), &type_info.package)?;
    let relative_name = relative_descriptor_name(&type_info.full_name, &type_info.package);
    Some(PythonReference {
        type_ref: format!("{module_path}.{relative_name}.ValueType"),
        module_path,
    })
}

fn python_module_path_for_file_name(file_name: Option<&str>, package: &str) -> Option<String> {
    if let Some(file_name) = file_name {
        let mut module_path = file_name.replace('/', ".");
        if let Some(stripped) = module_path.strip_suffix(".proto") {
            module_path = format!("{stripped}_pb2");
        }
        if let Some(suffix) = module_path.strip_prefix("temporal.") {
            module_path = format!("temporalio.{suffix}");
        }
        return Some(module_path);
    }

    if package.is_empty() {
        None
    } else if let Some(suffix) = package.strip_prefix("temporal.") {
        Some(format!("temporalio.{suffix}"))
    } else {
        Some(package.to_string())
    }
}

fn render_package(
    enums: &[&RenderedEnum],
    models: &[&RenderedModel],
    services: &[RenderedService<'_>],
    support_fragments: &[SupportFragmentSpec],
) -> Result<GeneratedFiles> {
    let mut files = BTreeMap::new();
    render_support_package(&mut files, support_fragments)?;
    let model_names = enums
        .iter()
        .map(|enumeration| enumeration.name.clone())
        .chain(models.iter().map(|model| model.name.clone()))
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect::<Vec<_>>();
    let resource_operation_owners = resource_operation_owners(services);
    let resource_names = services
        .iter()
        .flat_map(|service| {
            service
                .resources
                .iter()
                .map(|resource| resource.type_name.clone())
        })
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect::<Vec<_>>();
    let support_names = support_export_names(support_fragments);

    insert_generated_file(
        &mut files,
        "__init__.py",
        render_package_init(services, &resource_names, &resource_operation_owners),
    )?;
    insert_generated_file(
        &mut files,
        "models.py",
        render_models_module(enums, models, &support_names),
    )?;
    insert_generated_file(
        &mut files,
        "_resources/__init__.py",
        render_resources_package_init(services),
    )?;
    insert_generated_file(&mut files, "service.py", render_service_module(services))?;
    insert_generated_file(
        &mut files,
        "operations/__init__.py",
        render_operations_package_init(),
    )?;

    for service in services {
        for resource in &service.resources {
            let bound_operations = resource_bound_operations(service, resource);
            insert_generated_file(
                &mut files,
                format!("_resources/{}.py", resource_module_name(resource)),
                render_resource_module_file(
                    service,
                    resource,
                    &bound_operations,
                    &model_names,
                    &resource_names,
                    &support_names,
                ),
            )?;
        }
        for operation in &service.operations {
            if resource_operation_owners.contains_key(&operation_key(service.name, operation.name))
            {
                continue;
            }
            insert_generated_file(
                &mut files,
                format!("operations/{}.py", operation.attr_name),
                render_operation_module(
                    service,
                    operation,
                    &model_names,
                    &resource_names,
                    &support_names,
                ),
            )?;
        }
    }

    Ok(GeneratedFiles::directory(files))
}

fn operation_key(service_name: &str, operation_name: &str) -> String {
    format!("{service_name}::{operation_name}")
}

fn resource_module_name(resource: &PlannedResource) -> String {
    python_ident(&resource.name.to_snake_case())
}

fn resource_operation_owners(services: &[RenderedService<'_>]) -> BTreeMap<String, String> {
    let mut owners = BTreeMap::new();
    for service in services {
        for resource in &service.resources {
            let resource_module = resource_module_name(resource);
            for method in &resource.methods {
                if let PlannedResourceMethodBindingSpec::Operation { operation_name, .. } =
                    &method.binding
                {
                    owners.insert(
                        operation_key(service.name, operation_name),
                        resource_module.clone(),
                    );
                }
            }
        }
    }
    owners
}

fn insert_generated_file(
    files: &mut BTreeMap<std::path::PathBuf, String>,
    path: impl Into<std::path::PathBuf>,
    contents: String,
) -> Result<()> {
    let path = path.into();
    if files.insert(path.clone(), contents).is_some() {
        return Err(Error::GeneratedFileConflict { path });
    }
    Ok(())
}

fn render_support_package(
    files: &mut BTreeMap<std::path::PathBuf, String>,
    support_fragments: &[SupportFragmentSpec],
) -> Result<Vec<String>> {
    let mut module_names = Vec::new();
    for fragment in support_fragments {
        let module_name = support_module_name(fragment)?;
        insert_generated_file(
            files,
            format!("_support/{module_name}.py"),
            fragment.contents.clone(),
        )?;
        module_names.push(module_name);
    }

    if !module_names.is_empty() {
        let mut output = String::new();
        render_generated_file_header(&mut output);
        output.push('\n');
        for module_name in &module_names {
            output.push_str("from .");
            output.push_str(module_name);
            output.push_str(" import *  # noqa: F401,F403\n");
        }
        insert_generated_file(files, "_support/__init__.py", output)?;
    }

    Ok(module_names)
}

fn support_module_name(fragment: &SupportFragmentSpec) -> Result<String> {
    let path = Path::new(&fragment.path);
    let Some(file_name) = path.file_name() else {
        return Err(Error::InvalidGeneratedPath {
            path: path.to_path_buf(),
            reason: "support path must have a file name".to_string(),
        });
    };
    let Some(file_name) = file_name.to_str() else {
        return Err(Error::InvalidGeneratedPath {
            path: path.to_path_buf(),
            reason: "support path must be valid UTF-8".to_string(),
        });
    };
    let Some(module_name) = Path::new(file_name).file_stem() else {
        return Err(Error::InvalidGeneratedPath {
            path: path.to_path_buf(),
            reason: "support path must have a module stem".to_string(),
        });
    };
    let Some(module_name) = module_name.to_str() else {
        return Err(Error::InvalidGeneratedPath {
            path: path.to_path_buf(),
            reason: "support path must be valid UTF-8".to_string(),
        });
    };
    if Path::new(file_name)
        .extension()
        .and_then(|extension| extension.to_str())
        != Some("py")
    {
        return Err(Error::InvalidGeneratedPath {
            path: path.to_path_buf(),
            reason: "Python support files must end with `.py`".to_string(),
        });
    }
    if module_name.is_empty() {
        return Err(Error::InvalidGeneratedPath {
            path: path.to_path_buf(),
            reason: "support module name cannot be empty".to_string(),
        });
    }
    Ok(module_name.to_string())
}

fn render_generated_file_header(output: &mut String) {
    output.push_str(GENERATED_HEADER);
    output.push_str("\n# pyright: reportAny=false");
    output.push_str("\n\n");
    output.push_str("from __future__ import annotations\n");
}

fn render_python_module_imports(output: &mut String, module_imports: &BTreeSet<String>) {
    for import in module_imports {
        output.push_str("import ");
        output.push_str(import);
        output.push('\n');
    }
}

fn used_python_module_imports(body: &str, module_imports: &BTreeSet<String>) -> BTreeSet<String> {
    module_imports
        .iter()
        .filter(|module_import| body.contains(&format!("{module_import}.")))
        .cloned()
        .collect()
}

fn is_python_identifier_char(character: char) -> bool {
    character.is_ascii_alphanumeric() || character == '_'
}

fn body_uses_python_symbol(body: &str, symbol: &str) -> bool {
    body.match_indices(symbol).any(|(index, _)| {
        let previous = body[..index].chars().next_back();
        let next = body[index + symbol.len()..].chars().next();
        !previous.is_some_and(|character| is_python_identifier_char(character) || character == '.')
            && !next.is_some_and(is_python_identifier_char)
    })
}

fn used_python_symbol_imports(body: &str, candidates: &[String]) -> Vec<String> {
    candidates
        .iter()
        .filter(|candidate| body_uses_python_symbol(body, candidate))
        .cloned()
        .collect()
}

fn render_named_python_import(output: &mut String, module: &str, names: &[String]) {
    if names.is_empty() {
        return;
    }

    if names.len() == 1 {
        output.push_str("from ");
        output.push_str(module);
        output.push_str(" import ");
        output.push_str(&names[0]);
        output.push('\n');
        return;
    }

    output.push_str("from ");
    output.push_str(module);
    output.push_str(" import (\n");
    for name in names {
        output.push_str("    ");
        output.push_str(name);
        output.push_str(",\n");
    }
    output.push_str(")\n");
}

fn top_level_python_symbols(source: &str) -> BTreeSet<String> {
    let mut symbols = BTreeSet::new();

    for line in source.lines() {
        let line = line.trim_end();
        if line.is_empty()
            || line.starts_with(' ')
            || line.starts_with('\t')
            || line.starts_with('#')
            || line.starts_with('@')
            || line.starts_with("import ")
            || line.starts_with("from ")
        {
            continue;
        }

        if let Some(name) = line
            .strip_prefix("def ")
            .and_then(|line| line.split('(').next())
        {
            symbols.insert(name.trim().to_string());
            continue;
        }
        if let Some(name) = line
            .strip_prefix("class ")
            .and_then(|line| line.split(['(', ':']).next())
        {
            symbols.insert(name.trim().to_string());
            continue;
        }
        if let Some((name, _)) = line.split_once('=') {
            let name = name.trim();
            if !name.is_empty() && name.chars().all(is_python_identifier_char) {
                symbols.insert(name.to_string());
            }
        }
    }

    symbols
}

fn support_export_names(support_fragments: &[SupportFragmentSpec]) -> Vec<String> {
    support_fragments
        .iter()
        .flat_map(|fragment| top_level_python_symbols(&fragment.contents))
        .filter(|name| !name.starts_with('_'))
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect()
}

fn render_optional_python_imports(
    output: &mut String,
    body: &str,
    module_imports: &BTreeSet<String>,
) -> bool {
    let simple_imports = [
        ("import collections.abc\n", body.contains("collections.abc")),
        ("import dataclasses\n", body.contains("dataclasses.")),
        ("import enum\n", body.contains("enum.")),
        ("import typing\n", body.contains("typing.")),
        (
            "import typing_extensions\n",
            body.contains("typing_extensions."),
        ),
    ];
    let secondary_imports = [
        (
            "from datetime import timedelta\n",
            body.contains("timedelta"),
        ),
        (
            "import temporalio.common\n",
            body.contains("temporalio.common"),
        ),
        (
            "from temporalio import workflow\n",
            body.contains("workflow.Nexus")
                || body.contains("workflow.create_nexus_client")
                || body.contains("workflow.get_external_workflow_handle")
                || body.contains("workflow.info()")
                || body.contains("getattr(workflow, "),
        ),
    ];

    let mut wrote_any = false;
    for (import_line, used) in simple_imports {
        if used {
            output.push_str(import_line);
            wrote_any = true;
        }
    }
    for (import_line, used) in secondary_imports {
        if used {
            output.push_str(import_line);
            wrote_any = true;
        }
    }

    let used_module_imports = used_python_module_imports(body, module_imports);
    if !used_module_imports.is_empty() {
        render_python_module_imports(output, &used_module_imports);
        wrote_any = true;
    }

    wrote_any
}

fn render_models_module(
    enums: &[&RenderedEnum],
    models: &[&RenderedModel],
    support_names: &[String],
) -> String {
    let mut module_imports = BTreeSet::new();
    for model in models {
        module_imports.insert(model.proto_module_path.clone());
        for field in &model.fields {
            module_imports.extend(field.imports.module_imports.iter().cloned());
        }
    }
    let mut body = String::new();
    if !enums.is_empty() {
        if !body.is_empty() {
            body.push_str("\n\n");
        }
        for (index, enumeration) in enums.iter().enumerate() {
            render_enum(&mut body, enumeration);
            if index + 1 != enums.len() {
                body.push_str("\n\n");
            }
        }
    }

    if !models.is_empty() {
        if !body.is_empty() {
            body.push_str("\n\n");
        }
        for (index, model) in models.iter().enumerate() {
            render_model(&mut body, model);
            if index + 1 != models.len() {
                body.push_str("\n\n");
            }
        }
    }

    let mut output = String::new();
    render_generated_file_header(&mut output);
    output.push('\n');
    let wrote_imports = render_optional_python_imports(&mut output, &body, &module_imports);
    let used_support_names = used_python_symbol_imports(&body, support_names);
    if !used_support_names.is_empty() {
        if wrote_imports {
            output.push('\n');
        }
        render_named_python_import(&mut output, "._support", &used_support_names);
    }
    if !body.is_empty() {
        output.push('\n');
        output.push('\n');
        output.push_str(&body);
    }

    output
}

