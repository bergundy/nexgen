pub(crate) fn generate(
    api_plan: &ApiPlan,
    support_fragments: &[SupportFragmentSpec],
) -> Result<GeneratedFiles> {
    let mut enums = IndexMap::new();
    let mut models = IndexMap::new();
    let services = api_plan
        .services
        .iter()
        .map(|service| {
            let operations = service
                .operations
                .iter()
                .map(|operation| resolve_operation(operation, api_plan, &mut enums, &mut models))
                .collect::<Result<Vec<_>>>()?;

            Ok(RenderedService {
                name: &service.name,
                endpoint: service.endpoint.clone(),
                operations,
                resources: service.resources.clone(),
            })
        })
        .collect::<Result<Vec<_>>>()?;

    render_package(
        enums.values().collect::<Vec<_>>().as_slice(),
        models.values().collect::<Vec<_>>().as_slice(),
        &services,
        support_fragments,
    )
}

pub(crate) fn python_field_name(name: &str) -> String {
    python_ident(&name.to_snake_case())
}

#[derive(Debug)]
struct RenderedService<'a> {
    name: &'a str,
    endpoint: String,
    operations: Vec<RenderedOperation<'a>>,
    resources: Vec<PlannedResource>,
}

