fn optional_from_proto_expr(
    resolved_type: &ResolvedFieldType,
    proto_name: &str,
    field: &PlannedField,
) -> String {
    let has_presence = field.has_presence;
    match resolved_type.kind {
        ResolvedFieldKind::Message => {
            let from_proto = resolved_type
                .message_conversion
                .as_ref()
                .expect("message conversion should be present")
                .from_proto_expr(&format!("proto.{proto_name}"));
            if has_presence {
                format!("{from_proto} if proto.HasField(\"{proto_name}\") else None")
            } else {
                from_proto
            }
        }
        ResolvedFieldKind::Enum => {
            let from_proto = enum_from_proto_expr(resolved_type, &format!("proto.{proto_name}"));
            if has_presence {
                format!("{from_proto} if proto.HasField(\"{proto_name}\") else None")
            } else {
                from_proto
            }
        }
        _ => {
            if has_presence {
                format!("proto.{proto_name} if proto.HasField(\"{proto_name}\") else None")
            } else {
                format!("proto.{proto_name}")
            }
        }
    }
}

