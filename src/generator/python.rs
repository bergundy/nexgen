const GENERATED_HEADER: &str = "# Generated by nexus-rpc-gen. DO NOT EDIT!";
const PYTHON_SUPPORT_MARKER: &str = "# Appended from support.$pythonFile";

pub struct PythonBackend;

impl GeneratorBackend for PythonBackend {
    fn language(&self) -> Language {
        Language::Python
    }

    fn generate(
        &self,
        spec: &ApiSpec,
        descriptors: &DescriptorIndex,
        support: &SupportFiles,
    ) -> Result<String> {
        let requires_python_support = spec.services.iter().any(|service| !service.apis.is_empty());
        if requires_python_support && support.python.is_none() {
            return Err(Error::MissingPythonSupport);
        }

        let mut enums = IndexMap::new();
        let mut models = IndexMap::new();
        let services =
            spec.services
                .iter()
                .map(|service| {
                    let endpoint = service.endpoint.as_deref().ok_or_else(|| {
                        Error::MissingServiceEndpoint {
                            service: service.name.clone(),
                        }
                    })?;
                    let operations = service
                        .operations
                        .iter()
                        .map(|operation| {
                            resolve_operation(
                                &service.name,
                                operation,
                                descriptors,
                                &mut enums,
                                &mut models,
                            )
                        })
                        .collect::<Result<Vec<_>>>()?;
                    let operation_map: BTreeMap<&str, &RenderedOperation<'_>> = operations
                        .iter()
                        .map(|operation| (operation.name, operation))
                        .collect();
                    let apis = service
                        .apis
                        .iter()
                        .map(|api| resolve_api(&service.name, api, &operation_map))
                        .collect::<Result<Vec<_>>>()?;

                    Ok(RenderedService {
                        name: service.name.as_str(),
                        endpoint: endpoint.to_string(),
                        client_name: format!("{}Client", service.name),
                        operations,
                        apis,
                    })
                })
                .collect::<Result<Vec<_>>>()?;

        Ok(render_module(
            enums.values().collect::<Vec<_>>().as_slice(),
            models.values().collect::<Vec<_>>().as_slice(),
            &services,
            support.python.as_deref(),
        ))
    }
}

#[derive(Debug)]
struct RenderedService<'a> {
    name: &'a str,
    endpoint: String,
    client_name: String,
    operations: Vec<RenderedOperation<'a>>,
    apis: Vec<RenderedApi>,
}

#[derive(Debug)]
struct RenderedOperation<'a> {
    name: &'a str,
    attr_name: String,
    input_ref: &'a str,
    output_ref: &'a str,
    input_type_name: String,
    output_type_name: String,
    input_model_name: String,
    output_model_name: String,
    input_field_names: BTreeSet<String>,
}

#[derive(Debug)]
struct RenderedApi {
    attr_name: String,
    operation_attr_name: String,
    operation_output_model_name: String,
    output_ref: String,
    request_strategy: RenderedApiRequestStrategy,
    response_strategy: RenderedApiResponseStrategy,
    parameters: Vec<RenderedApiParameter>,
}

#[derive(Debug)]
struct RenderedApiParameter {
    name: String,
    property_name: String,
    type_name: Option<String>,
    python_converter: Option<String>,
    python_output_converter: Option<String>,
    annotation: String,
    default_expr: Option<String>,
    positional: bool,
}

#[derive(Debug)]
enum RenderedApiRequestStrategy {
    Converter(String),
    SinglePropertyConverter {
        parameter_name: String,
        converter: String,
        fallback_model_name: String,
    },
    ModelConstructor {
        model_name: String,
        fields: Vec<RenderedApiRequestField>,
    },
}

#[derive(Debug)]
struct RenderedApiRequestField {
    field_name: String,
    parameter_name: String,
    converter: Option<String>,
}

#[derive(Debug)]
enum RenderedApiResponseStrategy {
    Converter(String),
    SinglePropertyConverter(String),
}

#[derive(Debug)]
struct RenderedEnum {
    name: String,
    values: Vec<RenderedEnumValue>,
}

#[derive(Debug)]
struct RenderedEnumValue {
    name: String,
    number: i32,
}

#[derive(Debug)]
struct RenderedModel {
    name: String,
    proto_ref: String,
    proto_module_path: String,
    fields: Vec<RenderedField>,
}

#[derive(Debug)]
struct RenderedField {
    attr_name: String,
    annotation: String,
    default_expr: String,
    from_proto_expr: String,
    to_proto_lines: Vec<String>,
    imports: BTreeSet<String>,
}

#[derive(Debug)]
struct MapFieldInfo {
    key_type: ResolvedFieldType,
    value_type: ResolvedFieldType,
}

#[derive(Debug, Clone, PartialEq, Eq)]
enum ResolvedFieldKind {
    Scalar,
    Message,
    Enum,
    Unknown,
}

#[derive(Debug, Clone)]
struct ResolvedFieldType {
    annotation: String,
    proto_annotation: Option<String>,
    imports: BTreeSet<String>,
    kind: ResolvedFieldKind,
}

fn resolve_operation<'a>(
    service_name: &str,
    operation: &'a OperationSpec,
    descriptors: &DescriptorIndex,
    enums: &mut IndexMap<String, RenderedEnum>,
    models: &mut IndexMap<String, RenderedModel>,
) -> Result<RenderedOperation<'a>> {
    let input_ref = required_python_ref(service_name, operation, Direction::Input)?;
    let output_ref = required_python_ref(service_name, operation, Direction::Output)?;

    let input_message = descriptors.resolve_python_ref(input_ref)?;
    let output_message = descriptors.resolve_python_ref(output_ref)?;

    ensure_model(input_message, Some(input_ref), descriptors, enums, models);
    ensure_model(output_message, Some(output_ref), descriptors, enums, models);

    Ok(RenderedOperation {
        name: operation.name.as_str(),
        attr_name: python_ident(&operation.name.to_snake_case()),
        input_ref,
        output_ref,
        input_type_name: message_type_name(&input_message.full_name),
        output_type_name: message_type_name(&output_message.full_name),
        input_model_name: message_model_name(&input_message.full_name),
        output_model_name: message_model_name(&output_message.full_name),
        input_field_names: input_message
            .descriptor
            .field
            .iter()
            .filter_map(|field| field.name.as_deref())
            .map(python_ident)
            .collect(),
    })
}

fn resolve_api(
    service_name: &str,
    api: &ApiMethodSpec,
    operations: &BTreeMap<&str, &RenderedOperation<'_>>,
) -> Result<RenderedApi> {
    if api.input.schema_type != "object" {
        return Err(Error::UnsupportedApiInputType {
            service: service_name.to_string(),
            api: api.name.clone(),
            input_type: api.input.schema_type.clone(),
        });
    }

    let operation =
        operations
            .get(api.operation.as_str())
            .ok_or_else(|| Error::UnknownApiOperation {
                service: service_name.to_string(),
                api: api.name.clone(),
                operation: api.operation.clone(),
            })?;
    let output_ref = api
        .output
        .python_ref
        .as_deref()
        .filter(|value| !value.trim().is_empty())
        .ok_or_else(|| Error::MissingApiOutputPythonRef {
            service: service_name.to_string(),
            api: api.name.clone(),
        })?;

    let mut positional_required_parameters = Vec::new();
    let mut positional_defaulted_parameters = Vec::new();
    let mut keyword_only_parameters = Vec::new();
    for property in &api.input.properties {
        let annotation = property
            .python_type
            .clone()
            .or_else(|| property.schema_type.as_deref().map(api_property_annotation))
            .ok_or_else(|| Error::MissingApiInputPropertyType {
                service: service_name.to_string(),
                api: api.name.clone(),
                property: property.name.clone(),
            })?;

        let parameter = RenderedApiParameter {
            name: python_ident(&property.name.to_snake_case()),
            property_name: property.name.clone(),
            type_name: property.type_name.clone(),
            python_converter: property.python_converter.clone(),
            python_output_converter: property.python_output_converter.clone(),
            annotation,
            default_expr: property
                .python_default
                .clone()
                .or_else(|| property.default_value.as_ref().map(python_default_expr)),
            positional: property.positional,
        };
        match (parameter.positional, parameter.default_expr.is_some()) {
            (true, true) => positional_defaulted_parameters.push(parameter),
            (true, false) => positional_required_parameters.push(parameter),
            (false, _) => keyword_only_parameters.push(parameter),
        }
    }

    let mut parameters = Vec::new();
    parameters.extend(positional_required_parameters);
    parameters.extend(positional_defaulted_parameters);
    parameters.extend(keyword_only_parameters);

    let request_strategy = resolve_api_request_strategy(service_name, api, operation, &parameters)?;
    let response_strategy =
        resolve_api_response_strategy(service_name, api, operation, output_ref, &parameters)?;

    Ok(RenderedApi {
        attr_name: python_ident(&api.name.to_snake_case()),
        operation_attr_name: operation.attr_name.clone(),
        operation_output_model_name: operation.output_model_name.clone(),
        output_ref: output_ref.to_string(),
        request_strategy,
        response_strategy,
        parameters,
    })
}

fn render_api_parameter(output: &mut String, parameter: &RenderedApiParameter) {
    output.push_str("        ");
    output.push_str(&parameter.name);
    output.push_str(": ");
    output.push_str(&parameter.annotation);
    if let Some(default_expr) = &parameter.default_expr {
        output.push_str(" = ");
        output.push_str(default_expr);
    }
    output.push_str(",\n");
}

fn split_api_parameters(
    parameters: &[RenderedApiParameter],
) -> (Vec<&RenderedApiParameter>, Vec<&RenderedApiParameter>) {
    let positional = parameters
        .iter()
        .filter(|parameter| parameter.positional)
        .collect();
    let keyword_only = parameters
        .iter()
        .filter(|parameter| !parameter.positional)
        .collect();
    (positional, keyword_only)
}

fn resolve_api_request_strategy(
    service_name: &str,
    api: &ApiMethodSpec,
    operation: &RenderedOperation<'_>,
    parameters: &[RenderedApiParameter],
) -> Result<RenderedApiRequestStrategy> {
    if let Some(converter) = normalized_symbol(api.input.python_converter.as_deref()) {
        return Ok(RenderedApiRequestStrategy::Converter(converter.to_string()));
    }

    if parameters.len() == 1 {
        let parameter = &parameters[0];
        if parameter
            .type_name
            .as_deref()
            .is_some_and(|type_name| type_name.eq_ignore_ascii_case(&operation.input_type_name))
        {
            if let Some(converter) = normalized_symbol(parameter.python_converter.as_deref()) {
                return Ok(RenderedApiRequestStrategy::SinglePropertyConverter {
                    parameter_name: parameter.name.clone(),
                    converter: converter.to_string(),
                    fallback_model_name: operation.input_model_name.clone(),
                });
            }
        }
    }

    if !parameters.is_empty()
        && parameters.iter().all(|parameter| {
            operation
                .input_field_names
                .contains(&parameter.property_name)
        })
    {
        return Ok(RenderedApiRequestStrategy::ModelConstructor {
            model_name: operation.input_model_name.clone(),
            fields: parameters
                .iter()
                .map(|parameter| RenderedApiRequestField {
                    field_name: parameter.property_name.clone(),
                    parameter_name: parameter.name.clone(),
                    converter: normalized_symbol(parameter.python_converter.as_deref())
                        .map(str::to_string),
                })
                .collect(),
        });
    }

    Err(Error::MissingApiInputPythonConverter {
        service: service_name.to_string(),
        api: api.name.clone(),
    })
}

fn resolve_api_response_strategy(
    service_name: &str,
    api: &ApiMethodSpec,
    operation: &RenderedOperation<'_>,
    output_ref: &str,
    parameters: &[RenderedApiParameter],
) -> Result<RenderedApiResponseStrategy> {
    if let Some(converter) = normalized_symbol(api.output.python_converter.as_deref()) {
        return Ok(RenderedApiResponseStrategy::Converter(
            converter.to_string(),
        ));
    }

    if parameters.len() == 1 {
        let parameter = &parameters[0];
        if parameter
            .type_name
            .as_deref()
            .is_some_and(|type_name| type_name.eq_ignore_ascii_case(&operation.output_type_name))
            && parameter.annotation == output_ref
        {
            if let Some(converter) = normalized_symbol(parameter.python_output_converter.as_deref())
            {
                return Ok(RenderedApiResponseStrategy::SinglePropertyConverter(
                    converter.to_string(),
                ));
            }
        }
    }

    Err(Error::MissingApiOutputPythonConverter {
        service: service_name.to_string(),
        api: api.name.clone(),
    })
}

fn normalized_symbol(value: Option<&str>) -> Option<&str> {
    value.filter(|value| !value.trim().is_empty())
}

fn required_python_ref<'a>(
    service_name: &str,
    operation: &'a OperationSpec,
    direction: Direction,
) -> Result<&'a str> {
    operation
        .language_ref(Language::Python, direction)
        .ok_or_else(|| Error::MissingLanguageRef {
            service: service_name.to_string(),
            operation: operation.name.clone(),
            language: Language::Python,
            direction: direction.as_str(),
        })
}

fn ensure_model(
    message: &MessageMetadata,
    proto_ref_override: Option<&str>,
    descriptors: &DescriptorIndex,
    enums: &mut IndexMap<String, RenderedEnum>,
    models: &mut IndexMap<String, RenderedModel>,
) {
    if let Some(existing) = models.get_mut(&message.full_name) {
        if let Some(proto_ref) = proto_ref_override {
            existing.proto_ref = proto_ref.to_string();
        }
        return;
    }

    let proto_ref = proto_ref_override
        .map(str::to_string)
        .or_else(|| {
            message_python_ref(&message.full_name, descriptors).map(|reference| reference.type_ref)
        })
        .expect("descriptor messages should have a Python reference");
    let proto_module_path = proto_ref_override
        .map(module_path)
        .map(str::to_string)
        .or_else(|| {
            message_python_ref(&message.full_name, descriptors)
                .map(|reference| reference.module_path)
        })
        .expect("descriptor messages should have a Python module path");

    models.insert(
        message.full_name.clone(),
        RenderedModel {
            name: message_model_name(&message.full_name),
            proto_ref,
            proto_module_path,
            fields: Vec::new(),
        },
    );

    let fields = message
        .descriptor
        .field
        .iter()
        .map(|field| build_field(field, descriptors, enums, models))
        .collect();

    models
        .get_mut(&message.full_name)
        .expect("model should be inserted before recursive field resolution")
        .fields = fields;
}

fn ensure_enum(enumeration: &EnumMetadata, enums: &mut IndexMap<String, RenderedEnum>) {
    enums
        .entry(enumeration.full_name.clone())
        .or_insert_with(|| RenderedEnum {
            name: enum_name(&enumeration.full_name),
            values: enumeration
                .descriptor
                .value
                .iter()
                .filter_map(|value| {
                    Some(RenderedEnumValue {
                        name: value.name.as_deref()?.to_string(),
                        number: value.number?,
                    })
                })
                .collect(),
        });
}

fn build_field(
    field: &FieldDescriptorProto,
    descriptors: &DescriptorIndex,
    enums: &mut IndexMap<String, RenderedEnum>,
    models: &mut IndexMap<String, RenderedModel>,
) -> RenderedField {
    let proto_name = field
        .name
        .as_deref()
        .expect("descriptor fields should be named");
    let attr_name = python_ident(proto_name);

    if let Some(map_info) = map_field_info(field, descriptors, enums, models) {
        let mut imports = map_info.key_type.imports.clone();
        imports.extend(map_info.value_type.imports.iter().cloned());
        return RenderedField {
            attr_name: attr_name.clone(),
            annotation: format!(
                "dict[{}, {}]",
                map_info.key_type.annotation, map_info.value_type.annotation
            ),
            default_expr: "dataclasses.field(default_factory=dict)".to_string(),
            from_proto_expr: map_value_from_proto_expr(&map_info.value_type, proto_name),
            to_proto_lines: map_value_to_proto_lines(&map_info.value_type, &attr_name, proto_name),
            imports,
        };
    }

    let resolved_type = resolve_field_type(field, descriptors, enums, models);
    let label = field_label(field);

    if label == Some(Label::Repeated) {
        let annotation = format!("list[{}]", resolved_type.annotation);
        let to_proto_lines = match resolved_type.kind {
            ResolvedFieldKind::Message => vec![
                format!("if self.{attr_name}:"),
                format!("    for value in self.{attr_name}:"),
                format!("        item = message.{proto_name}.add()"),
                format!("        item.CopyFrom(value.to_proto())"),
            ],
            ResolvedFieldKind::Enum => vec![
                format!("if self.{attr_name}:"),
                format!(
                    "    message.{proto_name}.extend({} for value in self.{attr_name})",
                    enum_proto_value_expr(&resolved_type, "value")
                ),
            ],
            _ => vec![
                format!("if self.{attr_name}:"),
                format!("    message.{proto_name}.extend(self.{attr_name})"),
            ],
        };

        return RenderedField {
            attr_name: attr_name.clone(),
            annotation,
            default_expr: "dataclasses.field(default_factory=list)".to_string(),
            from_proto_expr: repeated_from_proto_expr(&resolved_type, proto_name),
            to_proto_lines,
            imports: resolved_type.imports,
        };
    }

    let annotation = format!("{} | None", resolved_type.annotation);
    let from_proto_expr = if resolved_type.kind == ResolvedFieldKind::Message
        && field_has_presence(field, field_type(field))
    {
        format!(
            "{}.from_proto(proto.{proto_name}) if proto.HasField(\"{proto_name}\") else None",
            resolved_type.annotation
        )
    } else if resolved_type.kind == ResolvedFieldKind::Message {
        format!(
            "{}.from_proto(proto.{proto_name})",
            resolved_type.annotation
        )
    } else if resolved_type.kind == ResolvedFieldKind::Enum
        && field_has_presence(field, field_type(field))
    {
        format!(
            "{}(proto.{proto_name}) if proto.HasField(\"{proto_name}\") else None",
            resolved_type.annotation
        )
    } else if resolved_type.kind == ResolvedFieldKind::Enum {
        format!("{}(proto.{proto_name})", resolved_type.annotation)
    } else if field_has_presence(field, field_type(field)) {
        format!("proto.{proto_name} if proto.HasField(\"{proto_name}\") else None")
    } else {
        format!("proto.{proto_name}")
    };

    let to_proto_lines = match resolved_type.kind {
        ResolvedFieldKind::Message => vec![
            format!("if self.{attr_name} is not None:"),
            format!("    message.{proto_name}.CopyFrom(self.{attr_name}.to_proto())"),
        ],
        ResolvedFieldKind::Enum => vec![
            format!("if self.{attr_name} is not None:"),
            format!(
                "    message.{proto_name} = {}",
                enum_proto_value_expr(&resolved_type, &format!("self.{attr_name}"))
            ),
        ],
        _ => vec![
            format!("if self.{attr_name} is not None:"),
            format!("    message.{proto_name} = self.{attr_name}"),
        ],
    };

    RenderedField {
        attr_name,
        annotation,
        default_expr: "None".to_string(),
        from_proto_expr,
        to_proto_lines,
        imports: resolved_type.imports,
    }
}

fn repeated_from_proto_expr(resolved_type: &ResolvedFieldType, proto_name: &str) -> String {
    match resolved_type.kind {
        ResolvedFieldKind::Message => format!(
            "[{}.from_proto(value) for value in proto.{proto_name}]",
            resolved_type.annotation
        ),
        ResolvedFieldKind::Enum => {
            format!(
                "[{}(value) for value in proto.{proto_name}]",
                resolved_type.annotation
            )
        }
        _ => format!("list(proto.{proto_name})"),
    }
}

fn map_value_from_proto_expr(map_value_type: &ResolvedFieldType, proto_name: &str) -> String {
    match map_value_type.kind {
        ResolvedFieldKind::Message => format!(
            "{{key: {}.from_proto(value) for key, value in proto.{proto_name}.items()}}",
            map_value_type.annotation
        ),
        ResolvedFieldKind::Enum => format!(
            "{{key: {}(value) for key, value in proto.{proto_name}.items()}}",
            map_value_type.annotation
        ),
        _ => format!("{{key: value for key, value in proto.{proto_name}.items()}}"),
    }
}

fn map_value_to_proto_lines(
    map_value_type: &ResolvedFieldType,
    attr_name: &str,
    proto_name: &str,
) -> Vec<String> {
    match map_value_type.kind {
        ResolvedFieldKind::Message => vec![
            format!("if self.{attr_name}:"),
            format!("    for key, value in self.{attr_name}.items():"),
            format!("        message.{proto_name}[key].CopyFrom(value.to_proto())"),
        ],
        ResolvedFieldKind::Enum => vec![
            format!("if self.{attr_name}:"),
            format!(
                "    message.{proto_name}.update({{key: {} for key, value in self.{attr_name}.items()}})",
                enum_proto_value_expr(map_value_type, "value")
            ),
        ],
        _ => vec![
            format!("if self.{attr_name}:"),
            format!("    message.{proto_name}.update(self.{attr_name})"),
        ],
    }
}

fn enum_proto_value_expr(resolved_type: &ResolvedFieldType, expr: &str) -> String {
    match &resolved_type.proto_annotation {
        Some(proto_annotation) => {
            format!("typing.cast({proto_annotation}, int({expr}))")
        }
        None => format!("int({expr})"),
    }
}

fn map_field_info(
    field: &FieldDescriptorProto,
    descriptors: &DescriptorIndex,
    enums: &mut IndexMap<String, RenderedEnum>,
    models: &mut IndexMap<String, RenderedModel>,
) -> Option<MapFieldInfo> {
    if field_label(field) != Some(Label::Repeated) || field_type(field) != Some(Type::Message) {
        return None;
    }

    let entry_name = field.type_name.as_deref()?.trim_start_matches('.');
    let entry = descriptors.message(entry_name)?;
    let is_map_entry = entry
        .descriptor
        .options
        .as_ref()
        .and_then(|options| options.map_entry)
        .unwrap_or(false);

    if !is_map_entry {
        return None;
    }

    let key_field = entry
        .descriptor
        .field
        .iter()
        .find(|field| field.name.as_deref() == Some("key"))?;
    let value_field = entry
        .descriptor
        .field
        .iter()
        .find(|field| field.name.as_deref() == Some("value"))?;

    Some(MapFieldInfo {
        key_type: resolve_field_type(key_field, descriptors, enums, models),
        value_type: resolve_field_type(value_field, descriptors, enums, models),
    })
}

fn resolve_field_type(
    field: &FieldDescriptorProto,
    descriptors: &DescriptorIndex,
    enums: &mut IndexMap<String, RenderedEnum>,
    models: &mut IndexMap<String, RenderedModel>,
) -> ResolvedFieldType {
    match field_type(field) {
        Some(Type::Double | Type::Float) => ResolvedFieldType {
            annotation: "float".to_string(),
            proto_annotation: None,
            imports: BTreeSet::new(),
            kind: ResolvedFieldKind::Scalar,
        },
        Some(
            Type::Int64
            | Type::Uint64
            | Type::Int32
            | Type::Fixed64
            | Type::Fixed32
            | Type::Uint32
            | Type::Sfixed32
            | Type::Sfixed64
            | Type::Sint32
            | Type::Sint64,
        ) => ResolvedFieldType {
            annotation: "int".to_string(),
            proto_annotation: None,
            imports: BTreeSet::new(),
            kind: ResolvedFieldKind::Scalar,
        },
        Some(Type::Bool) => ResolvedFieldType {
            annotation: "bool".to_string(),
            proto_annotation: None,
            imports: BTreeSet::new(),
            kind: ResolvedFieldKind::Scalar,
        },
        Some(Type::String) => ResolvedFieldType {
            annotation: "str".to_string(),
            proto_annotation: None,
            imports: BTreeSet::new(),
            kind: ResolvedFieldKind::Scalar,
        },
        Some(Type::Bytes) => ResolvedFieldType {
            annotation: "bytes".to_string(),
            proto_annotation: None,
            imports: BTreeSet::new(),
            kind: ResolvedFieldKind::Scalar,
        },
        Some(Type::Enum) => {
            if let Some(enumeration) = field
                .type_name
                .as_deref()
                .and_then(|type_name| descriptors.enumeration(type_name.trim_start_matches('.')))
            {
                ensure_enum(enumeration, enums);
                let reference = enum_python_ref(&enumeration.full_name, descriptors)
                    .expect("descriptor enums should have a Python reference");
                let mut imports = BTreeSet::new();
                imports.insert(reference.module_path);
                ResolvedFieldType {
                    annotation: enum_name(&enumeration.full_name),
                    proto_annotation: Some(reference.type_ref),
                    imports,
                    kind: ResolvedFieldKind::Enum,
                }
            } else {
                ResolvedFieldType {
                    annotation: "int".to_string(),
                    proto_annotation: None,
                    imports: BTreeSet::new(),
                    kind: ResolvedFieldKind::Enum,
                }
            }
        }
        Some(Type::Message) | Some(Type::Group) => {
            if let Some(message) = field
                .type_name
                .as_deref()
                .and_then(|type_name| descriptors.message(type_name.trim_start_matches('.')))
            {
                ensure_model(message, None, descriptors, enums, models);
                ResolvedFieldType {
                    annotation: message_model_name(&message.full_name),
                    proto_annotation: None,
                    imports: BTreeSet::new(),
                    kind: ResolvedFieldKind::Message,
                }
            } else {
                ResolvedFieldType {
                    annotation: "object".to_string(),
                    proto_annotation: None,
                    imports: BTreeSet::new(),
                    kind: ResolvedFieldKind::Unknown,
                }
            }
        }
        None => ResolvedFieldType {
            annotation: "object".to_string(),
            proto_annotation: None,
            imports: BTreeSet::new(),
            kind: ResolvedFieldKind::Unknown,
        },
    }
}

