#[derive(Debug)]
struct PythonReference {
    module_path: String,
    type_ref: String,
}

fn message_python_ref(type_name: &str, descriptors: &DescriptorIndex) -> Option<PythonReference> {
    let message = descriptors.message(type_name.trim_start_matches('.'))?;
    let module_path =
        python_module_path_for_file_name(message.file_name.as_deref(), &message.package)?;
    let relative_name = relative_descriptor_name(&message.full_name, &message.package);
    Some(PythonReference {
        type_ref: format!("{module_path}.{relative_name}"),
        module_path,
    })
}

fn enum_python_ref(type_name: &str, descriptors: &DescriptorIndex) -> Option<PythonReference> {
    let enumeration = descriptors.enumeration(type_name.trim_start_matches('.'))?;
    let module_path =
        python_module_path_for_file_name(enumeration.file_name.as_deref(), &enumeration.package)?;
    let relative_name = relative_descriptor_name(&enumeration.full_name, &enumeration.package);
    Some(PythonReference {
        type_ref: format!("{module_path}.{relative_name}.ValueType"),
        module_path,
    })
}

fn python_module_path_for_file_name(file_name: Option<&str>, package: &str) -> Option<String> {
    if let Some(file_name) = file_name {
        let mut module_path = file_name.replace('/', ".");
        if let Some(stripped) = module_path.strip_suffix(".proto") {
            module_path = format!("{stripped}_pb2");
        }
        if let Some(suffix) = module_path.strip_prefix("temporal.") {
            module_path = format!("temporalio.{suffix}");
        }
        return Some(module_path);
    }

    if package.is_empty() {
        None
    } else if let Some(suffix) = package.strip_prefix("temporal.") {
        Some(format!("temporalio.{suffix}"))
    } else {
        Some(package.to_string())
    }
}

fn relative_descriptor_name(full_name: &str, package: &str) -> String {
    if package.is_empty() {
        full_name.to_string()
    } else {
        full_name
            .strip_prefix(&format!("{package}."))
            .unwrap_or(full_name)
            .to_string()
    }
}

fn field_has_presence(field: &FieldDescriptorProto, field_type: Option<Type>) -> bool {
    matches!(field_type, Some(Type::Message))
        || field.proto3_optional.unwrap_or(false)
        || field.oneof_index.is_some()
}

fn field_label(field: &FieldDescriptorProto) -> Option<Label> {
    field.label.and_then(|label| Label::try_from(label).ok())
}

fn field_type(field: &FieldDescriptorProto) -> Option<Type> {
    field
        .r#type
        .and_then(|field_type| Type::try_from(field_type).ok())
}

fn render_module(
    enums: &[&RenderedEnum],
    models: &[&RenderedModel],
    services: &[RenderedService<'_>],
    support_source: Option<&str>,
) -> String {
    let mut imports = BTreeSet::new();
    for service in services {
        for operation in &service.operations {
            imports.insert(module_path(operation.input_ref).to_string());
            imports.insert(module_path(operation.output_ref).to_string());
        }
    }
    for model in models {
        imports.insert(model.proto_module_path.clone());
        for field in &model.fields {
            imports.extend(field.imports.iter().cloned());
        }
    }

    let mut output = String::new();
    output.push_str(GENERATED_HEADER);
    output.push_str("\n\n");
    output.push_str("from __future__ import annotations\n\n");
    output.push_str("import collections.abc\n");
    output.push_str("import dataclasses\n");
    if !enums.is_empty() {
        output.push_str("import enum\n");
    }
    output.push_str("import typing\n\n");
    output.push_str("from nexusrpc import Operation, service\n");
    output.push_str("from temporalio import workflow\n\n");

    for import in imports {
        output.push_str("import ");
        output.push_str(&import);
        output.push('\n');
    }

    if !enums.is_empty() {
        output.push_str("\n\n");
    }

    for (index, enumeration) in enums.iter().enumerate() {
        render_enum(&mut output, enumeration);
        if index + 1 != enums.len() {
            output.push_str("\n\n");
        }
    }

    if !enums.is_empty() && !models.is_empty() {
        output.push_str("\n\n");
    } else if !models.is_empty() {
        output.push_str("\n\n");
    }

    for (index, model) in models.iter().enumerate() {
        render_model(&mut output, model);
        if index + 1 != models.len() {
            output.push_str("\n\n");
        }
    }

    if !models.is_empty() && !services.is_empty() {
        output.push_str("\n\n");
    }

    for (service_index, service) in services.iter().enumerate() {
        render_service(&mut output, service);
        if service_index + 1 != services.len() {
            output.push_str("\n\n");
        }
    }

    output.push_str("\n\n");
    output.push_str("__nexus_operation_registry__: dict[\n");
    output.push_str("    tuple[str, str], ");
    output.push_str(&registry_operation_type(services));
    output.push('\n');
    output.push_str("] = {\n");

    for service in services {
        for operation in &service.operations {
            output.push_str("    (\n");
            output.push_str("        \"");
            output.push_str(service.name);
            output.push_str("\",\n");
            output.push_str("        \"");
            output.push_str(operation.name);
            output.push_str("\",\n");
            output.push_str("    ): ");
            output.push_str(service.name);
            output.push('.');
            output.push_str(&operation.attr_name);
            output.push_str(",\n");
        }
    }

    output.push_str("}\n");

    if let Some(support_source) = support_source.filter(|source| !source.trim().is_empty()) {
        output.push_str("\n\n");
        output.push_str(PYTHON_SUPPORT_MARKER);
        output.push('\n');
        output.push_str(support_source);
        if !support_source.ends_with('\n') {
            output.push('\n');
        }
    }

    output
}

fn render_enum(output: &mut String, enumeration: &RenderedEnum) {
    output.push_str("class ");
    output.push_str(&enumeration.name);
    output.push_str("(enum.IntEnum):\n");

    if enumeration.values.is_empty() {
        output.push_str("    pass\n");
        return;
    }

    for value in &enumeration.values {
        output.push_str("    ");
        output.push_str(&value.name);
        output.push_str(" = ");
        output.push_str(&value.number.to_string());
        output.push('\n');
    }
}

fn render_model(output: &mut String, model: &RenderedModel) {
    output.push_str("@dataclasses.dataclass(slots=True)\n");
    output.push_str("class ");
    output.push_str(&model.name);
    output.push_str(":\n");

    if model.fields.is_empty() {
        output.push_str("    @classmethod\n");
        output.push_str("    def from_proto(\n");
        output.push_str("        cls,\n");
        output.push_str("        proto: ");
        output.push_str(&model.proto_ref);
        output.push_str(",\n");
        output.push_str("    ) -> ");
        output.push_str(&model.name);
        output.push_str(":\n");
        output.push_str("        return cls()\n\n");
        output.push_str("    def to_proto(self) -> ");
        output.push_str(&model.proto_ref);
        output.push_str(":\n");
        output.push_str("        return ");
        output.push_str(&model.proto_ref);
        output.push_str("()\n");
        return;
    }

    for field in &model.fields {
        output.push_str("    ");
        output.push_str(&field.attr_name);
        output.push_str(": ");
        output.push_str(&field.annotation);
        output.push_str(" = ");
        output.push_str(&field.default_expr);
        output.push('\n');
    }

    output.push_str("\n");
    output.push_str("    @classmethod\n");
    output.push_str("    def from_proto(\n");
    output.push_str("        cls,\n");
    output.push_str("        proto: ");
    output.push_str(&model.proto_ref);
    output.push_str(",\n");
    output.push_str("    ) -> ");
    output.push_str(&model.name);
    output.push_str(":\n");
    output.push_str("        return cls(\n");

    for field in &model.fields {
        output.push_str("            ");
        output.push_str(&field.attr_name);
        output.push_str("=");
        output.push_str(&field.from_proto_expr);
        output.push_str(",\n");
    }

    output.push_str("        )\n\n");
    output.push_str("    def to_proto(self) -> ");
    output.push_str(&model.proto_ref);
    output.push_str(":\n");
    output.push_str("        message = ");
    output.push_str(&model.proto_ref);
    output.push_str("()\n");

    for field in &model.fields {
        for line in &field.to_proto_lines {
            output.push_str("        ");
            output.push_str(line);
            output.push('\n');
        }
    }

    output.push_str("        return message\n");
}

fn render_service(output: &mut String, service: &RenderedService<'_>) {
    output.push_str("@service\n");
    output.push_str("class ");
    output.push_str(service.name);
    output.push_str(":\n");

    if service.operations.is_empty() {
        output.push_str("    pass\n");
    } else {
        for (operation_index, operation) in service.operations.iter().enumerate() {
            output.push_str("    ");
            output.push_str(&operation.attr_name);
            output.push_str(": Operation[\n");
            output.push_str("        ");
            output.push_str(operation.input_ref);
            output.push_str(",\n");
            output.push_str("        ");
            output.push_str(operation.output_ref);
            output.push_str(",\n");
            output.push_str("    ] = Operation(name=\"");
            output.push_str(operation.name);
            output.push_str("\")\n");

            if operation_index + 1 != service.operations.len() {
                output.push('\n');
            }
        }
    }

    output.push_str("\n\n");
    output.push_str("class ");
    output.push_str(&service.client_name);
    output.push_str(":\n");
    output.push_str("    def __init__(self) -> None:\n");
    output.push_str("        self._client: workflow.NexusClient[");
    output.push_str(service.name);
    output.push_str("] = workflow.create_nexus_client(\n");
    output.push_str("            service=");
    output.push_str(service.name);
    output.push_str(",\n");
    output.push_str("            endpoint=");
    output.push_str(&python_string_literal(&service.endpoint));
    output.push_str(",\n");
    output.push_str("        )\n");

    if service.operations.is_empty() && service.apis.is_empty() {
        output.push('\n');
        output.push_str("    pass\n");
        return;
    }

    for operation in &service.operations {
        output.push('\n');
        render_operation_client_methods(output, service.name, operation);
    }

    for api in &service.apis {
        output.push('\n');
        render_api_client_method(output, api);
    }
}

fn render_operation_client_methods(
    output: &mut String,
    service_name: &str,
    operation: &RenderedOperation<'_>,
) {
    output.push_str("    async def ");
    output.push_str(&operation.attr_name);
    output.push_str("(\n");
    output.push_str("        self,\n");
    output.push_str("        request: ");
    output.push_str(&operation.input_model_name);
    output.push_str(",\n");
    output.push_str("    ) -> workflow.NexusOperationHandle[\n");
    output.push_str("        ");
    output.push_str(operation.output_ref);
    output.push_str(",\n");
    output.push_str("    ]:\n");
    output.push_str("        return await self._client.start_operation(\n");
    output.push_str("            ");
    output.push_str(service_name);
    output.push('.');
    output.push_str(&operation.attr_name);
    output.push_str(",\n");
    output.push_str("            request.to_proto(),\n");
    output.push_str("        )\n");
}

fn render_api_client_method(output: &mut String, api: &RenderedApi) {
    let (positional_parameters, keyword_only_parameters) = split_api_parameters(&api.parameters);

    output.push_str("    async def ");
    output.push_str(&api.attr_name);
    output.push_str("(\n");
    output.push_str("        self,\n");

    if api.parameters.is_empty() {
        output.push_str("    ) -> ");
        output.push_str(&api.output_ref);
        output.push_str(":\n");
    } else {
        for parameter in positional_parameters {
            render_api_parameter(output, parameter);
        }
        if !keyword_only_parameters.is_empty() {
            output.push_str("        *,\n");
            for parameter in keyword_only_parameters {
                render_api_parameter(output, parameter);
            }
        }
        output.push_str("    ) -> ");
        output.push_str(&api.output_ref);
        output.push_str(":\n");
    }

    render_api_request(output, &api.request_strategy, &api.parameters);
    output.push_str("        handle = await self.");
    output.push_str(&api.operation_attr_name);
    output.push_str("(request)\n");
    output.push_str("        response_proto = await handle\n");
    output.push_str("        response = ");
    output.push_str(&api.operation_output_model_name);
    output.push_str(".from_proto(response_proto)\n");
    render_api_response(output, &api.response_strategy);
}

fn render_api_request(
    output: &mut String,
    strategy: &RenderedApiRequestStrategy,
    parameters: &[RenderedApiParameter],
) {
    match strategy {
        RenderedApiRequestStrategy::Converter(converter) => {
            output.push_str("        request = ");
            output.push_str(converter);
            output.push_str("(\n");
            for parameter in parameters {
                output.push_str("            ");
                output.push_str(&parameter.name);
                output.push_str("=");
                output.push_str(&parameter.name);
                output.push_str(",\n");
            }
            output.push_str("        )\n");
        }
        RenderedApiRequestStrategy::SinglePropertyConverter {
            parameter_name,
            converter,
            fallback_model_name,
        } => {
            output.push_str("        request = ");
            output.push_str(converter);
            output.push('(');
            output.push_str(parameter_name);
            output.push_str(")\n");
            output.push_str("        if request is None:\n");
            output.push_str("            request = ");
            output.push_str(fallback_model_name);
            output.push_str("()\n");
        }
        RenderedApiRequestStrategy::ModelConstructor { model_name, fields } => {
            output.push_str("        request = ");
            output.push_str(model_name);
            output.push_str("(\n");
            for field in fields {
                output.push_str("            ");
                output.push_str(&field.field_name);
                output.push('=');
                if let Some(converter) = &field.converter {
                    output.push_str(converter);
                    output.push('(');
                    output.push_str(&field.parameter_name);
                    output.push(')');
                } else {
                    output.push_str(&field.parameter_name);
                }
                output.push_str(",\n");
            }
            output.push_str("        )\n");
        }
    }
}

fn render_api_response(output: &mut String, strategy: &RenderedApiResponseStrategy) {
    match strategy {
        RenderedApiResponseStrategy::Converter(converter) => {
            output.push_str("        return ");
            output.push_str(converter);
            output.push_str("(\n");
            output.push_str("            request=request,\n");
            output.push_str("            response=response,\n");
            output.push_str("        )\n");
        }
        RenderedApiResponseStrategy::SinglePropertyConverter(converter) => {
            output.push_str("        return ");
            output.push_str(converter);
            output.push_str("(response)\n");
        }
    }
}

fn module_path(reference: &str) -> &str {
    reference
        .rsplit_once('.')
        .map(|(module, _)| module)
        .unwrap_or(reference)
}

fn registry_operation_type(services: &[RenderedService<'_>]) -> String {
    let operation_types = services
        .iter()
        .flat_map(|service| &service.operations)
        .map(|operation| {
            format!(
                "Operation[{}, {}]",
                operation.input_ref, operation.output_ref
            )
        })
        .collect::<BTreeSet<_>>();

    if operation_types.is_empty() {
        "Operation[object, object]".to_string()
    } else {
        operation_types.into_iter().collect::<Vec<_>>().join(" | ")
    }
}

fn python_ident(name: &str) -> String {
    if is_python_keyword(name) {
        format!("{name}_")
    } else {
        name.to_string()
    }
}

fn python_string_literal(value: &str) -> String {
    format!("{value:?}")
}

