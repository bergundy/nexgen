const GENERATED_HEADER: &str = "// Generated by nexus-rpc-gen. DO NOT EDIT!";
const TYPESCRIPT_SUPPORT_MARKER: &str = "// Included from support.$typescriptFile";

pub struct TypeScriptBackend;

impl GeneratorBackend for TypeScriptBackend {
    fn language(&self) -> Language {
        Language::TypeScript
    }

    fn generate(
        &self,
        spec: &ApiSpec,
        descriptors: &DescriptorIndex,
        support: &SupportFiles,
    ) -> Result<String> {
        let mut enums = IndexMap::new();
        let mut models = IndexMap::new();
        let mut uses_long = false;
        let root_model_capabilities =
            root_model_capabilities(spec, descriptors, Language::TypeScript)?;
        let services =
            spec.services
                .iter()
                .map(|service| {
                    let endpoint = service.endpoint.as_deref().ok_or_else(|| {
                        Error::MissingServiceEndpoint {
                            service: service.name.clone(),
                        }
                    })?;
                    let operations = service
                        .operations
                        .iter()
                        .map(|operation| {
                            resolve_operation(
                                &service.name,
                                operation,
                                spec,
                                descriptors,
                                &root_model_capabilities,
                                &mut enums,
                                &mut models,
                                &mut uses_long,
                            )
                        })
                        .collect::<Result<Vec<_>>>()?;

                    Ok(RenderedService {
                        name: service.name.as_str(),
                        endpoint: endpoint.to_string(),
                        client_name: format!("{}Client", service.name),
                        operations,
                    })
                })
                .collect::<Result<Vec<_>>>()?;

        Ok(render_module(
            enums.values().collect::<Vec<_>>().as_slice(),
            models.values().collect::<Vec<_>>().as_slice(),
            &services,
            uses_long,
            support.typescript.as_deref(),
        ))
    }
}

#[derive(Debug)]
struct RenderedService<'a> {
    name: &'a str,
    endpoint: String,
    client_name: String,
    operations: Vec<RenderedOperation<'a>>,
}

#[derive(Debug)]
struct RenderedOperation<'a> {
    name: &'a str,
    attr_name: String,
    input_proto_ref: String,
    output_proto_ref: String,
    input_annotation: String,
    input_to_proto_expr: String,
}

#[derive(Debug)]
struct RenderedEnum {
    name: String,
    values: Vec<RenderedEnumValue>,
}

#[derive(Debug)]
struct RenderedEnumValue {
    name: String,
    number: i32,
}

#[derive(Debug)]
struct RenderedModel {
    name: String,
    capabilities: ModelCapabilities,
    fields: Vec<RenderedField>,
    sourced_fields: Vec<RenderedSourcedField>,
}

#[derive(Debug)]
struct RenderedField {
    name: String,
    annotation: String,
    optional: bool,
    from_proto_expr: String,
    to_proto_expr: String,
}

#[derive(Debug)]
struct RenderedSourcedField {
    name: String,
    to_proto_expr: String,
}

#[derive(Debug)]
struct MapFieldInfo {
    value_type: ResolvedFieldType,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum ResolvedFieldKind {
    Scalar,
    Message,
    Enum,
    Unknown,
}

#[derive(Debug, Clone)]
struct ResolvedFieldType {
    annotation: String,
    kind: ResolvedFieldKind,
    uses_long: bool,
    message_conversion: Option<MessageValueConversion>,
    enum_conversion: Option<EnumValueConversion>,
}

#[derive(Debug, Clone)]
enum MessageValueConversionKind {
    GeneratedModel {
        model_name: String,
    },
    Override {
        from_proto: String,
        to_proto: String,
    },
}

#[derive(Debug, Clone)]
struct MessageValueConversion {
    annotation: String,
    kind: MessageValueConversionKind,
}

impl MessageValueConversion {
    fn from_proto_expr(&self, proto_expr: &str) -> String {
        match &self.kind {
            MessageValueConversionKind::GeneratedModel { model_name } => {
                format!("{model_name}.fromProto({proto_expr})")
            }
            MessageValueConversionKind::Override { from_proto, .. } => {
                format!("{from_proto}({proto_expr})")
            }
        }
    }

    fn to_proto_expr(&self, value_expr: &str) -> String {
        match &self.kind {
            MessageValueConversionKind::GeneratedModel { model_name } => {
                format!("{model_name}.toProto({value_expr}) ?? {{}}")
            }
            MessageValueConversionKind::Override { to_proto, .. } => {
                format!("{to_proto}({value_expr})")
            }
        }
    }
}

#[derive(Debug, Clone)]
struct EnumValueConversion {
    from_proto: String,
    to_proto: String,
}

impl EnumValueConversion {
    fn from_proto_expr(&self, proto_expr: &str) -> String {
        format!("{}({proto_expr})", self.from_proto)
    }

    fn to_proto_expr(&self, value_expr: &str) -> String {
        format!("{}({value_expr})", self.to_proto)
    }
}

fn resolve_operation<'a>(
    service_name: &str,
    operation: &'a OperationSpec,
    spec: &ApiSpec,
    descriptors: &DescriptorIndex,
    root_model_capabilities: &BTreeMap<String, ModelCapabilities>,
    enums: &mut IndexMap<String, RenderedEnum>,
    models: &mut IndexMap<String, RenderedModel>,
    uses_long: &mut bool,
) -> Result<RenderedOperation<'a>> {
    let input_ref = required_typescript_ref(service_name, operation, Direction::Input)?;
    let output_ref = required_typescript_ref(service_name, operation, Direction::Output)?;

    let input_message = descriptors.resolve_typescript_ref(input_ref)?;
    let output_message = descriptors.resolve_typescript_ref(output_ref)?;

    let input_conversion = resolve_message_value_conversion(
        input_message,
        root_model_capabilities
            .get(&input_message.full_name)
            .copied()
            .unwrap_or(ModelCapabilities::TO_PROTO_ONLY),
        spec,
        descriptors,
        enums,
        models,
        uses_long,
    );
    let _output_conversion = resolve_message_value_conversion(
        output_message,
        root_model_capabilities
            .get(&output_message.full_name)
            .copied()
            .unwrap_or(ModelCapabilities::BIDIRECTIONAL),
        spec,
        descriptors,
        enums,
        models,
        uses_long,
    );

    Ok(RenderedOperation {
        name: operation.name.as_str(),
        attr_name: typescript_ident(&operation.name.to_lower_camel_case()),
        input_proto_ref: message_typescript_interface_ref(input_message),
        output_proto_ref: message_typescript_interface_ref(output_message),
        input_annotation: input_conversion.annotation.clone(),
        input_to_proto_expr: input_conversion.to_proto_expr("request"),
    })
}

fn required_typescript_ref<'a>(
    service_name: &str,
    operation: &'a OperationSpec,
    direction: Direction,
) -> Result<&'a str> {
    operation
        .language_ref(Language::TypeScript, direction)
        .ok_or_else(|| Error::MissingLanguageRef {
            service: service_name.to_string(),
            operation: operation.name.clone(),
            language: Language::TypeScript,
            direction: direction.as_str(),
        })
}

fn resolve_message_value_conversion(
    message: &MessageMetadata,
    requested_capabilities: ModelCapabilities,
    spec: &ApiSpec,
    descriptors: &DescriptorIndex,
    enums: &mut IndexMap<String, RenderedEnum>,
    models: &mut IndexMap<String, RenderedModel>,
    uses_long: &mut bool,
) -> MessageValueConversion {
    if let Some(language_override) = spec
        .type_override(&message.full_name)
        .and_then(|type_override| type_override.language_override(Language::TypeScript))
    {
        return MessageValueConversion {
            annotation: language_override.type_name.clone(),
            kind: MessageValueConversionKind::Override {
                from_proto: language_override.from_proto.clone(),
                to_proto: language_override.to_proto.clone(),
            },
        };
    }

    ensure_model(
        message,
        requested_capabilities,
        spec,
        descriptors,
        enums,
        models,
        uses_long,
    );
    MessageValueConversion {
        annotation: message_model_name(&message.full_name),
        kind: MessageValueConversionKind::GeneratedModel {
            model_name: message_model_name(&message.full_name),
        },
    }
}

fn ensure_model(
    message: &MessageMetadata,
    requested_capabilities: ModelCapabilities,
    spec: &ApiSpec,
    descriptors: &DescriptorIndex,
    enums: &mut IndexMap<String, RenderedEnum>,
    models: &mut IndexMap<String, RenderedModel>,
    uses_long: &mut bool,
) {
    if spec
        .type_override(&message.full_name)
        .and_then(|type_override| type_override.language_override(Language::TypeScript))
        .is_some()
    {
        return;
    }

    if let Some(existing) = models.get_mut(&message.full_name) {
        existing.capabilities.merge(requested_capabilities);
        return;
    }

    models.insert(
        message.full_name.clone(),
        RenderedModel {
            name: message_model_name(&message.full_name),
            capabilities: requested_capabilities,
            fields: Vec::new(),
            sourced_fields: Vec::new(),
        },
    );

    let fields = message
        .descriptor
        .field
        .iter()
        .filter(|field| {
            let proto_name = field
                .name
                .as_deref()
                .expect("descriptor fields should be named");
            !spec
                .type_override(&message.full_name)
                .is_some_and(|type_override| {
                    type_override.is_field_hidden(Language::TypeScript, proto_name)
                })
        })
        .map(|field| build_field(message, field, spec, descriptors, enums, models, uses_long))
        .collect();

    let sourced_fields = message
        .descriptor
        .field
        .iter()
        .filter_map(|field| {
            let proto_name = field
                .name
                .as_deref()
                .expect("descriptor fields should be named");
            spec.type_override(&message.full_name)
                .and_then(|type_override| {
                    type_override.field_source(Language::TypeScript, proto_name)
                })
                .map(|source_expr| {
                    build_sourced_field(
                        message,
                        field,
                        source_expr,
                        spec,
                        descriptors,
                        enums,
                        models,
                        uses_long,
                    )
                })
        })
        .collect();

    models
        .get_mut(&message.full_name)
        .expect("model should be inserted before recursive field resolution")
        .fields = fields;
    models
        .get_mut(&message.full_name)
        .expect("model should be inserted before recursive field resolution")
        .sourced_fields = sourced_fields;
}

fn ensure_enum(enumeration: &EnumMetadata, enums: &mut IndexMap<String, RenderedEnum>) {
    enums
        .entry(enumeration.full_name.clone())
        .or_insert_with(|| RenderedEnum {
            name: enum_name(&enumeration.full_name),
            values: enumeration
                .descriptor
                .value
                .iter()
                .filter_map(|value| {
                    Some(RenderedEnumValue {
                        name: value.name.as_deref()?.to_string(),
                        number: value.number?,
                    })
                })
                .collect(),
        });
}

fn build_field(
    message: &MessageMetadata,
    field: &FieldDescriptorProto,
    spec: &ApiSpec,
    descriptors: &DescriptorIndex,
    enums: &mut IndexMap<String, RenderedEnum>,
    models: &mut IndexMap<String, RenderedModel>,
    uses_long: &mut bool,
) -> RenderedField {
    let proto_name = field
        .name
        .as_deref()
        .expect("descriptor fields should be named");
    let field_name = typescript_field_name(field);
    let required = spec
        .type_override(&message.full_name)
        .is_some_and(|type_override| type_override.is_field_required(proto_name));

    if let Some(map_info) = map_field_info(field, spec, descriptors, enums, models, uses_long) {
        *uses_long |= map_info.value_type.uses_long;
        return RenderedField {
            name: field_name.clone(),
            annotation: typescript_field_annotation(
                spec,
                &message.full_name,
                proto_name,
                format!("Record<string, {}>", map_info.value_type.annotation),
            ),
            optional: true,
            from_proto_expr: map_value_from_proto_expr(&map_info.value_type, &field_name),
            to_proto_expr: map_value_to_proto_expr(&map_info.value_type, &field_name),
        };
    }

    let resolved_type = resolve_field_type(field, spec, descriptors, enums, models, uses_long);
    *uses_long |= resolved_type.uses_long;
    let label = field_label(field);
    let owner_name = message_model_name(&message.full_name);

    if label == Some(Label::Repeated) {
        return RenderedField {
            name: field_name.clone(),
            annotation: typescript_field_annotation(
                spec,
                &message.full_name,
                proto_name,
                format!("{}[]", resolved_type.annotation),
            ),
            optional: true,
            from_proto_expr: repeated_from_proto_expr(&resolved_type, &field_name),
            to_proto_expr: repeated_to_proto_expr(&resolved_type, &field_name),
        };
    }

    if required {
        return RenderedField {
            name: field_name.clone(),
            annotation: typescript_field_annotation(
                spec,
                &message.full_name,
                proto_name,
                resolved_type.annotation.clone(),
            ),
            optional: false,
            from_proto_expr: required_from_proto_expr(
                &resolved_type,
                &owner_name,
                &field_name,
                field,
            ),
            to_proto_expr: required_to_proto_expr(&resolved_type, &owner_name, &field_name),
        };
    }

    RenderedField {
        name: field_name.clone(),
        annotation: typescript_field_annotation(
            spec,
            &message.full_name,
            proto_name,
            resolved_type.annotation.clone(),
        ),
        optional: true,
        from_proto_expr: optional_from_proto_expr(&resolved_type, &field_name),
        to_proto_expr: optional_to_proto_expr(&resolved_type, &field_name),
    }
}

fn build_sourced_field(
    _message: &MessageMetadata,
    field: &FieldDescriptorProto,
    source_expr: &str,
    spec: &ApiSpec,
    descriptors: &DescriptorIndex,
    enums: &mut IndexMap<String, RenderedEnum>,
    models: &mut IndexMap<String, RenderedModel>,
    uses_long: &mut bool,
) -> RenderedSourcedField {
    let field_name = typescript_field_name(field);

    if let Some(map_info) = map_field_info(field, spec, descriptors, enums, models, uses_long) {
        *uses_long |= map_info.value_type.uses_long;
        return RenderedSourcedField {
            name: field_name.clone(),
            to_proto_expr: map_value_to_proto_expr_from_expr(&map_info.value_type, source_expr),
        };
    }

    let resolved_type = resolve_field_type(field, spec, descriptors, enums, models, uses_long);
    *uses_long |= resolved_type.uses_long;

    if field_label(field) == Some(Label::Repeated) {
        return RenderedSourcedField {
            name: field_name.clone(),
            to_proto_expr: repeated_to_proto_expr_from_expr(&resolved_type, source_expr),
        };
    }

    RenderedSourcedField {
        name: field_name,
        to_proto_expr: optional_to_proto_expr_from_expr(&resolved_type, source_expr),
    }
}

fn typescript_field_annotation(
    spec: &ApiSpec,
    message_name: &str,
    field_name: &str,
    default_annotation: String,
) -> String {
    spec.type_override(message_name)
        .and_then(|type_override| type_override.typescript_generated_model())
        .and_then(|typescript_model| typescript_model.field_annotation(field_name))
        .map(str::to_string)
        .unwrap_or(default_annotation)
}

fn repeated_from_proto_expr(resolved_type: &ResolvedFieldType, field_name: &str) -> String {
    match resolved_type.kind {
        ResolvedFieldKind::Message => format!(
            "proto.{field_name}?.map((value: any) => {})",
            resolved_type
                .message_conversion
                .as_ref()
                .expect("message conversion should be present")
                .from_proto_expr("value")
        ),
        ResolvedFieldKind::Enum => format!(
            "proto.{field_name}?.map((value: any) => {})",
            enum_from_proto_expr(resolved_type, "value")
        ),
        _ => format!("proto.{field_name}?.slice()"),
    }
}

fn repeated_to_proto_expr(resolved_type: &ResolvedFieldType, field_name: &str) -> String {
    repeated_to_proto_expr_from_expr(resolved_type, &format!("model.{field_name}"))
}

fn repeated_to_proto_expr_from_expr(resolved_type: &ResolvedFieldType, value_expr: &str) -> String {
    match resolved_type.kind {
        ResolvedFieldKind::Message => format!(
            "{value_expr}?.map((value) => {})",
            resolved_type
                .message_conversion
                .as_ref()
                .expect("message conversion should be present")
                .to_proto_expr("value")
        ),
        ResolvedFieldKind::Enum => format!(
            "{value_expr}?.map((value) => {})",
            enum_to_proto_expr(resolved_type, "value")
        ),
        _ => format!("{value_expr}?.slice()"),
    }
}

fn map_value_from_proto_expr(map_value_type: &ResolvedFieldType, field_name: &str) -> String {
    let value_expr = match map_value_type.kind {
        ResolvedFieldKind::Message => map_value_type
            .message_conversion
            .as_ref()
            .expect("message conversion should be present")
            .from_proto_expr("value"),
        ResolvedFieldKind::Enum => enum_from_proto_expr(map_value_type, "value"),
        _ => format!("value as {}", map_value_type.annotation),
    };
    format!(
        "proto.{field_name} == null ? undefined : (Object.fromEntries(Object.entries(proto.{field_name} as Record<string, any>).map(([key, value]: [string, any]) => [key, {value_expr}])) as Record<string, {}>)",
        map_value_type.annotation
    )
}

fn map_value_to_proto_expr(map_value_type: &ResolvedFieldType, field_name: &str) -> String {
    map_value_to_proto_expr_from_expr(map_value_type, &format!("model.{field_name}"))
}

fn map_value_to_proto_expr_from_expr(
    map_value_type: &ResolvedFieldType,
    value_expr: &str,
) -> String {
    let mapped_value_expr = match map_value_type.kind {
        ResolvedFieldKind::Message => map_value_type
            .message_conversion
            .as_ref()
            .expect("message conversion should be present")
            .to_proto_expr("value"),
        ResolvedFieldKind::Enum => enum_to_proto_expr(map_value_type, "value"),
        _ => "value".to_string(),
    };
    format!(
        "{value_expr} == null ? undefined : Object.fromEntries(Object.entries({value_expr} as Record<string, any>).map(([key, value]: [string, any]) => [key, {mapped_value_expr}]))"
    )
}

fn required_from_proto_expr(
    resolved_type: &ResolvedFieldType,
    owner_name: &str,
    field_name: &str,
    field: &FieldDescriptorProto,
) -> String {
    let required_proto = if field_has_presence(field, field_type(field)) {
        required_field_expr(&format!("proto.{field_name}"), owner_name, field_name)
    } else {
        match resolved_type.kind {
            ResolvedFieldKind::Scalar if resolved_type.annotation == "string" => {
                required_field_expr(
                    &format!("proto.{field_name} === '' ? undefined : proto.{field_name}"),
                    owner_name,
                    field_name,
                )
            }
            ResolvedFieldKind::Scalar if resolved_type.annotation == "Uint8Array" => {
                required_field_expr(
                    &format!(
                        "proto.{field_name} == null || proto.{field_name}.length === 0 ? undefined : proto.{field_name}"
                    ),
                    owner_name,
                    field_name,
                )
            }
            _ => required_field_expr(
                &format!("proto.{field_name} ?? undefined"),
                owner_name,
                field_name,
            ),
        }
    };
    match resolved_type.kind {
        ResolvedFieldKind::Message => required_field_expr(
            &resolved_type
                .message_conversion
                .as_ref()
                .expect("message conversion should be present")
                .from_proto_expr(&required_proto),
            owner_name,
            field_name,
        ),
        ResolvedFieldKind::Enum => required_field_expr(
            &enum_from_proto_expr(resolved_type, &required_proto),
            owner_name,
            field_name,
        ),
        _ => required_field_expr(
            &format!("proto.{field_name} ?? undefined"),
            owner_name,
            field_name,
        ),
    }
}

fn required_to_proto_expr(
    resolved_type: &ResolvedFieldType,
    owner_name: &str,
    field_name: &str,
) -> String {
    let required_value =
        required_field_expr(&format!("model.{field_name}"), owner_name, field_name);
    match resolved_type.kind {
        ResolvedFieldKind::Message => resolved_type
            .message_conversion
            .as_ref()
            .expect("message conversion should be present")
            .to_proto_expr(&required_value),
        ResolvedFieldKind::Enum => enum_to_proto_expr(resolved_type, &required_value),
        _ => required_value,
    }
}

fn optional_from_proto_expr(resolved_type: &ResolvedFieldType, field_name: &str) -> String {
    match resolved_type.kind {
        ResolvedFieldKind::Message => format!(
            "proto.{field_name} == null ? undefined : {}",
            resolved_type
                .message_conversion
                .as_ref()
                .expect("message conversion should be present")
                .from_proto_expr(&format!("proto.{field_name}"))
        ),
        ResolvedFieldKind::Enum => format!(
            "proto.{field_name} == null ? undefined : {}",
            enum_from_proto_expr(resolved_type, &format!("proto.{field_name}"))
        ),
        _ => format!("proto.{field_name} ?? undefined"),
    }
}

fn optional_to_proto_expr(resolved_type: &ResolvedFieldType, field_name: &str) -> String {
    optional_to_proto_expr_from_expr(resolved_type, &format!("model.{field_name}"))
}

fn optional_to_proto_expr_from_expr(resolved_type: &ResolvedFieldType, value_expr: &str) -> String {
    match resolved_type.kind {
        ResolvedFieldKind::Message => format!(
            "{value_expr} == null ? undefined : {}",
            resolved_type
                .message_conversion
                .as_ref()
                .expect("message conversion should be present")
                .to_proto_expr(value_expr)
        ),
        ResolvedFieldKind::Enum => format!(
            "{value_expr} == null ? undefined : {}",
            enum_to_proto_expr(resolved_type, value_expr)
        ),
        _ => value_expr.to_string(),
    }
}

fn enum_from_proto_expr(resolved_type: &ResolvedFieldType, expr: &str) -> String {
    if let Some(enum_conversion) = &resolved_type.enum_conversion {
        enum_conversion.from_proto_expr(expr)
    } else {
        format!("{expr} as {}", resolved_type.annotation)
    }
}

fn enum_to_proto_expr(resolved_type: &ResolvedFieldType, expr: &str) -> String {
    if let Some(enum_conversion) = &resolved_type.enum_conversion {
        enum_conversion.to_proto_expr(expr)
    } else {
        format!("{expr} as number")
    }
}

fn map_field_info(
    field: &FieldDescriptorProto,
    spec: &ApiSpec,
    descriptors: &DescriptorIndex,
    enums: &mut IndexMap<String, RenderedEnum>,
    models: &mut IndexMap<String, RenderedModel>,
    uses_long: &mut bool,
) -> Option<MapFieldInfo> {
    if field_label(field) != Some(Label::Repeated) || field_type(field) != Some(Type::Message) {
        return None;
    }

    let entry_name = field.type_name.as_deref()?.trim_start_matches('.');
    let entry = descriptors.message(entry_name)?;
    let is_map_entry = entry
        .descriptor
        .options
        .as_ref()
        .and_then(|options| options.map_entry)
        .unwrap_or(false);

    if !is_map_entry {
        return None;
    }

    let value_field = entry
        .descriptor
        .field
        .iter()
        .find(|field| field.name.as_deref() == Some("value"))?;

    Some(MapFieldInfo {
        value_type: resolve_field_type(value_field, spec, descriptors, enums, models, uses_long),
    })
}

fn resolve_field_type(
    field: &FieldDescriptorProto,
    spec: &ApiSpec,
    descriptors: &DescriptorIndex,
    enums: &mut IndexMap<String, RenderedEnum>,
    models: &mut IndexMap<String, RenderedModel>,
    uses_long: &mut bool,
) -> ResolvedFieldType {
    match field_type(field) {
        Some(Type::Double | Type::Float) => ResolvedFieldType {
            annotation: "number".to_string(),
            kind: ResolvedFieldKind::Scalar,
            uses_long: false,
            message_conversion: None,
            enum_conversion: None,
        },
        Some(Type::Int64 | Type::Uint64 | Type::Fixed64 | Type::Sfixed64 | Type::Sint64) => {
            *uses_long = true;
            ResolvedFieldType {
                annotation: "Long".to_string(),
                kind: ResolvedFieldKind::Scalar,
                uses_long: true,
                message_conversion: None,
                enum_conversion: None,
            }
        }
        Some(Type::Int32 | Type::Fixed32 | Type::Uint32 | Type::Sfixed32 | Type::Sint32) => {
            ResolvedFieldType {
                annotation: "number".to_string(),
                kind: ResolvedFieldKind::Scalar,
                uses_long: false,
                message_conversion: None,
                enum_conversion: None,
            }
        }
        Some(Type::Bool) => ResolvedFieldType {
            annotation: "boolean".to_string(),
            kind: ResolvedFieldKind::Scalar,
            uses_long: false,
            message_conversion: None,
            enum_conversion: None,
        },
        Some(Type::String) => ResolvedFieldType {
            annotation: "string".to_string(),
            kind: ResolvedFieldKind::Scalar,
            uses_long: false,
            message_conversion: None,
            enum_conversion: None,
        },
        Some(Type::Bytes) => ResolvedFieldType {
            annotation: "Uint8Array".to_string(),
            kind: ResolvedFieldKind::Scalar,
            uses_long: false,
            message_conversion: None,
            enum_conversion: None,
        },
        Some(Type::Enum) => {
            if let Some(enumeration) = field
                .type_name
                .as_deref()
                .and_then(|type_name| descriptors.enumeration(type_name.trim_start_matches('.')))
            {
                if let Some(language_override) = spec
                    .type_override(&enumeration.full_name)
                    .and_then(|type_override| type_override.language_override(Language::TypeScript))
                {
                    ResolvedFieldType {
                        annotation: language_override.type_name.clone(),
                        kind: ResolvedFieldKind::Enum,
                        uses_long: false,
                        message_conversion: None,
                        enum_conversion: Some(EnumValueConversion {
                            from_proto: language_override.from_proto.clone(),
                            to_proto: language_override.to_proto.clone(),
                        }),
                    }
                } else {
                    ensure_enum(enumeration, enums);
                    ResolvedFieldType {
                        annotation: enum_name(&enumeration.full_name),
                        kind: ResolvedFieldKind::Enum,
                        uses_long: false,
                        message_conversion: None,
                        enum_conversion: None,
                    }
                }
            } else {
                ResolvedFieldType {
                    annotation: "number".to_string(),
                    kind: ResolvedFieldKind::Enum,
                    uses_long: false,
                    message_conversion: None,
                    enum_conversion: None,
                }
            }
        }
        Some(Type::Message) | Some(Type::Group) => {
            if let Some(message) = field
                .type_name
                .as_deref()
                .and_then(|type_name| descriptors.message(type_name.trim_start_matches('.')))
            {
                let conversion = resolve_message_value_conversion(
                    message,
                    ModelCapabilities::BIDIRECTIONAL,
                    spec,
                    descriptors,
                    enums,
                    models,
                    uses_long,
                );
                ResolvedFieldType {
                    annotation: conversion.annotation.clone(),
                    kind: ResolvedFieldKind::Message,
                    uses_long: false,
                    message_conversion: Some(conversion),
                    enum_conversion: None,
                }
            } else {
                ResolvedFieldType {
                    annotation: "unknown".to_string(),
                    kind: ResolvedFieldKind::Unknown,
                    uses_long: false,
                    message_conversion: None,
                    enum_conversion: None,
                }
            }
        }
        None => ResolvedFieldType {
            annotation: "unknown".to_string(),
            kind: ResolvedFieldKind::Unknown,
            uses_long: false,
            message_conversion: None,
            enum_conversion: None,
        },
    }
}

fn message_model_name(full_name: &str) -> String {
    full_name
        .rsplit('.')
        .next()
        .expect("descriptor names should not be empty")
        .to_string()
}

fn enum_name(full_name: &str) -> String {
    full_name
        .rsplit('.')
        .next()
        .expect("descriptor names should not be empty")
        .to_string()
}

fn message_typescript_interface_ref(message: &MessageMetadata) -> String {
    let relative_name = relative_descriptor_name(&message.full_name, &message.package);
    let mut parts = relative_name.split('.').collect::<Vec<_>>();
    let leaf = parts
        .pop()
        .expect("descriptor names should not be empty")
        .to_string();
    if parts.is_empty() {
        format!("{}.I{leaf}", message.package)
    } else {
        format!("{}.{}.I{leaf}", message.package, parts.join("."))
    }
}

fn relative_descriptor_name(full_name: &str, package: &str) -> String {
    if package.is_empty() {
        full_name.to_string()
    } else {
        full_name
            .strip_prefix(&format!("{package}."))
            .unwrap_or(full_name)
            .to_string()
    }
}

fn field_label(field: &FieldDescriptorProto) -> Option<Label> {
    field.label.and_then(|label| Label::try_from(label).ok())
}

fn field_has_presence(field: &FieldDescriptorProto, field_type: Option<Type>) -> bool {
    matches!(field_type, Some(Type::Message))
        || field.proto3_optional.unwrap_or(false)
        || field.oneof_index.is_some()
}

fn field_type(field: &FieldDescriptorProto) -> Option<Type> {
    field
        .r#type
        .and_then(|field_type| Type::try_from(field_type).ok())
}

fn render_module(
    enums: &[&RenderedEnum],
    models: &[&RenderedModel],
    services: &[RenderedService<'_>],
    uses_long: bool,
    support_source: Option<&str>,
) -> String {
    let default_imports = [
        "import * as common from '@temporalio/common';",
        "import * as nexus from 'nexus-rpc';",
        "import type Long from 'long';",
        "import type { google, temporal } from '@temporalio/proto';",
        "import * as workflow from '@temporalio/workflow';",
    ];

    let mut output = String::new();
    output.push_str(GENERATED_HEADER);
    output.push_str("\n\n");
    output.push_str(default_imports[0]);
    output.push('\n');
    output.push_str(default_imports[1]);
    output.push('\n');
    if uses_long {
        output.push_str(default_imports[2]);
        output.push('\n');
    }
    output.push_str(default_imports[3]);
    output.push('\n');
    output.push_str(default_imports[4]);
    output.push('\n');

    if let Some(support_source) = support_source.filter(|source| !source.trim().is_empty()) {
        output.push('\n');
        output.push_str(TYPESCRIPT_SUPPORT_MARKER);
        output.push('\n');
        output.push_str(support_source);
        if !support_source.ends_with('\n') {
            output.push('\n');
        }
    }

    output.push_str("\n");
    output.push_str("function requiredField<T>(\n");
    output.push_str("  value: T | null | undefined,\n");
    output.push_str("  owner: string,\n");
    output.push_str("  field: string,\n");
    output.push_str("): T {\n");
    output.push_str("  if (value == null) {\n");
    output.push_str("    throw new Error(`missing required field ${owner}.${field}`);\n");
    output.push_str("  }\n");
    output.push_str("  return value;\n");
    output.push_str("}\n");

    if !enums.is_empty() {
        output.push('\n');
        for enumeration in enums {
            render_enum(&mut output, enumeration);
            output.push('\n');
        }
    }

    if !models.is_empty() {
        output.push('\n');
        for model in models {
            render_model(&mut output, model);
            output.push('\n');
        }
    }

    for (index, service) in services.iter().enumerate() {
        if index > 0 || !services.is_empty() {
            output.push('\n');
        }
        render_service(&mut output, service);
    }

    output
}

fn render_enum(output: &mut String, enumeration: &RenderedEnum) {
    output.push_str("export enum ");
    output.push_str(&enumeration.name);
    output.push_str(" {\n");
    if enumeration.values.is_empty() {
        output.push_str("}\n");
        return;
    }
    for value in &enumeration.values {
        output.push_str("  ");
        output.push_str(&value.name);
        output.push_str(" = ");
        output.push_str(&value.number.to_string());
        output.push_str(",\n");
    }
    output.push_str("}\n");
}

fn render_model(output: &mut String, model: &RenderedModel) {
    output.push_str("export interface ");
    output.push_str(&model.name);
    output.push_str(" {\n");
    for field in &model.fields {
        output.push_str("  ");
        output.push_str(&field.name);
        if field.optional {
            output.push('?');
        }
        output.push_str(": ");
        output.push_str(&field.annotation);
        output.push_str(";\n");
    }
    output.push_str("}\n\n");
    output.push_str("export const ");
    output.push_str(&model.name);
    output.push_str(" = {\n");
    let mut wrote_method = false;
    if model.capabilities.from_proto {
        output.push_str("  fromProto(\n");
        output.push_str("    proto: any,\n");
        output.push_str("  ): ");
        output.push_str(&model.name);
        output.push_str(" | undefined {\n");
        output.push_str("    if (proto == null) {\n");
        output.push_str("      return undefined;\n");
        output.push_str("    }\n");
        if model.fields.is_empty() {
            output.push_str("    return {};\n");
        } else {
            output.push_str("    return {\n");
            for field in &model.fields {
                output.push_str("      ");
                output.push_str(&field.name);
                output.push_str(": ");
                output.push_str(&field.from_proto_expr);
                output.push_str(",\n");
            }
            output.push_str("    };\n");
        }
        output.push_str("  }");
        wrote_method = true;
    }
    if model.capabilities.to_proto {
        if wrote_method {
            output.push_str(",\n\n");
        }
        output.push_str("  toProto(\n");
        output.push_str("    model: ");
        output.push_str(&model.name);
        output.push_str(" | null | undefined,\n");
        output.push_str("  ): any {\n");
        output.push_str("    if (model == null) {\n");
        output.push_str("      return undefined;\n");
        output.push_str("    }\n");
        if model.fields.is_empty() && model.sourced_fields.is_empty() {
            output.push_str("    return {};\n");
        } else {
            output.push_str("    return {\n");
            for field in &model.fields {
                output.push_str("      ");
                output.push_str(&field.name);
                output.push_str(": ");
                output.push_str(&field.to_proto_expr);
                output.push_str(",\n");
            }
            for field in &model.sourced_fields {
                output.push_str("      ");
                output.push_str(&field.name);
                output.push_str(": ");
                output.push_str(&field.to_proto_expr);
                output.push_str(",\n");
            }
            output.push_str("    };\n");
        }
        output.push_str("  }");
    }
    output.push('\n');
    output.push_str("};\n");
}

fn render_service(output: &mut String, service: &RenderedService<'_>) {
    output.push_str("export const ");
    output.push_str(service.name);
    output.push_str(" = nexus.service('");
    output.push_str(service.name);
    output.push_str("', {\n");
    for operation in &service.operations {
        output.push_str("  ");
        output.push_str(&operation.attr_name);
        output.push_str(": nexus.operation<\n");
        output.push_str("    ");
        output.push_str(&operation.input_proto_ref);
        output.push_str(",\n");
        output.push_str("    ");
        output.push_str(&operation.output_proto_ref);
        output.push('\n');
        output.push_str("  >({ name: ");
        output.push_str(&typescript_string_literal(operation.name));
        output.push_str(" }),\n");
    }
    output.push_str("});\n\n");

    output.push_str("export class ");
    output.push_str(&service.client_name);
    output.push_str(" {\n");
    output.push_str("  private readonly client: workflow.NexusServiceClient<typeof ");
    output.push_str(service.name);
    output.push_str(">;\n\n");
    output.push_str("  public constructor() {\n");
    output.push_str("    this.client = workflow.createNexusServiceClient({\n");
    output.push_str("      service: ");
    output.push_str(service.name);
    output.push_str(",\n");
    output.push_str("      endpoint: ");
    output.push_str(&typescript_string_literal(&service.endpoint));
    output.push_str(",\n");
    output.push_str("    });\n");
    output.push_str("  }\n");

    if service.operations.is_empty() {
        output.push('\n');
        output.push_str("}\n");
        return;
    }

    for operation in &service.operations {
        output.push('\n');
        render_operation_client_methods(output, service.name, operation);
    }

    output.push_str("}\n");
}

fn render_operation_client_methods(
    output: &mut String,
    service_name: &str,
    operation: &RenderedOperation<'_>,
) {
    output.push_str("  public async ");
    output.push_str(&operation.attr_name);
    output.push_str("(\n");
    output.push_str("    request: ");
    output.push_str(&operation.input_annotation);
    output.push_str(",\n");
    output.push_str("  ): Promise<workflow.NexusOperationHandle<");
    output.push_str(&operation.output_proto_ref);
    output.push_str(">> {\n");
    output.push_str("    return await this.client.startOperation(\n");
    output.push_str("      ");
    output.push_str(service_name);
    output.push_str(".operations.");
    output.push_str(&operation.attr_name);
    output.push_str(",\n");
    output.push_str("      ");
    output.push_str(&operation.input_to_proto_expr);
    output.push_str(",\n");
    output.push_str("    );\n");
    output.push_str("  }\n");
}

fn required_field_expr(value_expr: &str, owner_name: &str, field_name: &str) -> String {
    format!(
        "requiredField({value_expr}, {}, {})",
        typescript_string_literal(owner_name),
        typescript_string_literal(field_name)
    )
}

fn typescript_field_name(field: &FieldDescriptorProto) -> String {
    let json_name = field
        .json_name
        .as_deref()
        .or_else(|| field.name.as_deref())
        .expect("descriptor fields should be named");
    typescript_ident(json_name)
}

fn typescript_ident(name: &str) -> String {
    if is_typescript_keyword(name) {
        format!("{name}_")
    } else {
        name.to_string()
    }
}

fn typescript_string_literal(value: &str) -> String {
    format!("{value:?}")
}

fn is_typescript_keyword(name: &str) -> bool {
    matches!(
        name,
        "break"
            | "case"
            | "catch"
            | "class"
            | "const"
            | "continue"
            | "debugger"
            | "default"
            | "delete"
            | "do"
            | "else"
            | "enum"
            | "export"
            | "extends"
            | "false"
            | "finally"
            | "for"
            | "function"
            | "if"
            | "import"
            | "in"
            | "instanceof"
            | "new"
            | "null"
            | "return"
            | "super"
            | "switch"
            | "this"
            | "throw"
            | "true"
            | "try"
            | "typeof"
            | "var"
            | "void"
            | "while"
            | "with"
            | "yield"
            | "as"
            | "implements"
            | "interface"
            | "let"
            | "package"
            | "private"
            | "protected"
            | "public"
            | "static"
    )
}

